// Gentables copies the immutable IQ2 decoding tables from a pinned oracle.
package main

import (
	"crypto/sha256"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
)

func main() {
	source := flag.String("source", os.Getenv("DS4_CPU_ORACLE_SOURCE"), "pinned ds4.c path (default DS4_CPU_ORACLE_SOURCE)")
	out := flag.String("out", "iq2_tables.go", "output file")
	flag.Parse()
	if err := run(*source, *out); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(source, out string) error {
	b, err := os.ReadFile(source)
	if err != nil {
		return err
	}
	if fmt.Sprintf("%x", sha256.Sum256(b)) != "62e458f2c416148c0882f7247c7b16f9820054b0c2ae41374a9209541fe7a4c7" {
		return fmt.Errorf("source differs from pinned antirez/ds4 11e8cad")
	}
	s := "// Code generated by go generate from antirez/ds4 11e8cad; DO NOT EDIT.\npackage dsv4cpu\n"
	for _, x := range []struct{ name, typ, count string }{{"ksigns_iq2xs", "uint8", "128"}, {"iq2xxs_grid", "uint64", "256"}} {
		r := regexp.MustCompile(x.name + `\[` + x.count + `\]\s*=\s*\{([^}]+)\}`)
		m := r.FindSubmatch(b)
		if m == nil {
			return fmt.Errorf("missing table %s", x.name)
		}
		s += fmt.Sprintf("var %s = [%s]%s{%s}\n", x.name, x.count, x.typ, m[1])
	}
	f, err := format.Source([]byte(s))
	if err != nil {
		return err
	}
	return os.WriteFile(out, f, 0644)
}

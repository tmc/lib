// Genunicode writes unicode_tables.go from pinned Unicode Character Database
// files: Unicode 16.0.0 letter and number categories, and the Unicode 9.0.0
// NFC data that Hugging Face tokenizers 0.22.2 uses.
//
// Each input is checked against the URL and SHA-256 recorded in sources.json
// and cached under ~/tmp/hftokenizer-unicode. Run it from the hftokenizer
// directory:
//
//	go run ./internal/genunicode
package main

import (
	"bytes"
	"cmp"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"log"
	"maps"
	"net/http"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

type source struct {
	URL    string `json:"url"`
	SHA256 string `json:"sha256"`
}

var (
	cacheDir = flag.String("cache", "", "download cache (default ~/tmp/hftokenizer-unicode)")
	sources  map[string]source
)

func main() {
	log.SetFlags(0)
	log.SetPrefix("genunicode: ")
	flag.Parse()
	if *cacheDir == "" {
		home, err := os.UserHomeDir()
		if err != nil {
			log.Fatal(err)
		}
		*cacheDir = filepath.Join(home, "tmp", "hftokenizer-unicode")
	}
	data, err := os.ReadFile("internal/genunicode/sources.json")
	if err != nil {
		log.Fatal(err)
	}
	if err := json.Unmarshal(data, &sources); err != nil {
		log.Fatalf("parse sources.json: %v", err)
	}
	if err := os.MkdirAll(*cacheDir, 0o755); err != nil {
		log.Fatal(err)
	}

	var letter, number [][2]rune
	for _, r := range records("16.0.0") {
		switch r.fields[2][0] {
		case 'L':
			letter = append(letter, [2]rune{r.lo, r.hi})
		case 'N':
			number = append(number, [2]rune{r.lo, r.hi})
		}
	}

	type class struct {
		r   rune
		ccc int
	}
	var ccc []class
	decomp := make(map[rune][]rune)
	for _, r := range records("9.0.0") {
		c := atoi(r.fields[3])
		if c != 0 {
			for x := r.lo; x <= r.hi; x++ {
				ccc = append(ccc, class{x, c})
			}
		}
		if f := r.fields[5]; f != "" && !strings.HasPrefix(f, "<") {
			var parts []rune
			for _, p := range strings.Fields(f) {
				parts = append(parts, hexRune(p))
			}
			decomp[r.lo] = parts
		}
	}

	excluded := make(map[rune]bool)
	for _, line := range strings.Split(read("9.0.0", "DerivedNormalizationProps.txt"), "\n") {
		line, _, _ = strings.Cut(line, "#")
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		fields := strings.Split(line, ";")
		if strings.TrimSpace(fields[1]) != "Full_Composition_Exclusion" {
			continue
		}
		lo, hi, ok := strings.Cut(strings.TrimSpace(fields[0]), "..")
		if !ok {
			hi = lo
		}
		for x := hexRune(lo); x <= hexRune(hi); x++ {
			excluded[x] = true
		}
	}
	type composition struct{ a, b, r rune }
	var compositions []composition
	for r, parts := range decomp {
		if len(parts) == 2 && !excluded[r] {
			compositions = append(compositions, composition{parts[0], parts[1], r})
		}
	}
	slices.SortFunc(compositions, func(x, y composition) int {
		return cmp.Or(cmp.Compare(x.a, y.a), cmp.Compare(x.b, y.b))
	})

	var b bytes.Buffer
	b.WriteString("// Code generated by internal/genunicode. DO NOT EDIT.\n")
	b.WriteString("// Unicode 16.0.0 categories; Unicode 9.0.0 NFC (HF tokenizers 0.22.2).\n")
	b.WriteString("// See UNICODE-LICENSE.txt.\n\npackage hftokenizer\n\n")
	for _, t := range []struct {
		name   string
		ranges [][2]rune
	}{{"letterRanges", letter}, {"numberRanges", number}} {
		fmt.Fprintf(&b, "var %s = [...]runeRange{\n", t.name)
		for _, r := range collapse(t.ranges) {
			fmt.Fprintf(&b, "\t{%#x, %#x},\n", r[0], r[1])
		}
		b.WriteString("}\n\n")
	}
	b.WriteString("var combiningClasses = map[rune]uint8{\n")
	for _, c := range ccc {
		fmt.Fprintf(&b, "\t%#x: %d,\n", c.r, c.ccc)
	}
	b.WriteString("}\n\nvar canonicalDecompositions = map[rune][]rune{\n")
	for _, r := range slices.Sorted(maps.Keys(decomp)) {
		var parts []string
		for _, p := range decomp[r] {
			parts = append(parts, fmt.Sprintf("%#x", p))
		}
		fmt.Fprintf(&b, "\t%#x: {%s},\n", r, strings.Join(parts, ", "))
	}
	b.WriteString("}\n\nvar canonicalCompositions = map[[2]rune]rune{\n")
	for _, c := range compositions {
		fmt.Fprintf(&b, "\t{%#x, %#x}: %#x,\n", c.a, c.b, c.r)
	}
	b.WriteString("}\n")
	if err := os.WriteFile("unicode_tables.go", b.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
	fmt.Println("category ranges", len(collapse(letter))+len(collapse(number)), "CCC", len(ccc),
		"decompositions", len(decomp), "compositions", len(compositions))
}

type record struct {
	lo, hi rune
	fields []string
}

// records returns the UnicodeData.txt entries of version, with each
// "<..., First>"/"<..., Last>" pair folded into one range.
func records(version string) []record {
	var out []record
	pending := rune(-1)
	for _, line := range strings.Split(strings.TrimSuffix(read(version, "UnicodeData.txt"), "\n"), "\n") {
		fields := strings.Split(line, ";")
		r := hexRune(fields[0])
		if strings.HasSuffix(fields[1], ", First>") {
			pending = r
			continue
		}
		lo := r
		if strings.HasSuffix(fields[1], ", Last>") {
			lo = pending
		}
		pending = -1
		out = append(out, record{lo, r, fields})
	}
	return out
}

// read returns the named UCD file of version, downloading it into the cache
// if needed and checking it against sources.json.
func read(version, name string) string {
	key := version + "/" + name
	want, ok := sources[key]
	if !ok {
		log.Fatalf("%s: not in sources.json", key)
	}
	url := "https://www.unicode.org/Public/" + version + "/ucd/" + name
	path := filepath.Join(*cacheDir, version+"-"+name)
	data, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		data, err = download(url)
		if err == nil {
			err = os.WriteFile(path, data, 0o644)
		}
	}
	if err != nil {
		log.Fatal(err)
	}
	sum := sha256.Sum256(data)
	if url != want.URL || hex.EncodeToString(sum[:]) != want.SHA256 {
		log.Fatalf("%s: Unicode input hash mismatch", key)
	}
	return string(data)
}

func download(url string) ([]byte, error) {
	resp, err := http.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("get %s: %s", url, resp.Status)
	}
	return io.ReadAll(resp.Body)
}

// collapse merges adjacent ranges.
func collapse(ranges [][2]rune) [][2]rune {
	var out [][2]rune
	for _, r := range ranges {
		if n := len(out); n > 0 && out[n-1][1]+1 == r[0] {
			out[n-1][1] = r[1]
			continue
		}
		out = append(out, r)
	}
	return out
}

func hexRune(s string) rune {
	v, err := strconv.ParseUint(strings.TrimSpace(s), 16, 32)
	if err != nil {
		log.Fatal(err)
	}
	return rune(v)
}

func atoi(s string) int {
	v, err := strconv.Atoi(s)
	if err != nil {
		log.Fatal(err)
	}
	return v
}

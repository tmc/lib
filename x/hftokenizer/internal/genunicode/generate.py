#!/usr/bin/env python3
"""Generate pinned HF-compatible Unicode tables; no third-party Python modules."""
import argparse,hashlib,json,urllib.request
from pathlib import Path
root=Path(__file__).resolve().parents[2]
args=argparse.ArgumentParser()
args.add_argument('--cache',type=Path,default=Path.home()/'tmp/hftokenizer-unicode')
cache=args.parse_args().cache
expected=json.loads((root/'internal/genunicode/sources.json').read_text())
cache.mkdir(parents=True,exist_ok=True)
manifest={}
def read(version,name):
 url='https://www.unicode.org/Public/'+version+'/ucd/'+name
 p=cache/(version+'-'+name)
 if not p.exists():
  with urllib.request.urlopen(url) as response:data=response.read()
  p.write_bytes(data)
 data=p.read_bytes()
 receipt={'url':url,'sha256':hashlib.sha256(data).hexdigest()}
 if receipt!=expected[version+'/'+name]:raise ValueError('Unicode input hash mismatch: '+version+'/'+name)
 manifest[version+'/'+name]=receipt
 return data.decode()
def records(version):
 pending=None
 for line in read(version,'UnicodeData.txt').splitlines():
  fields=line.split(';');r=int(fields[0],16)
  if fields[1].endswith(', First>'):pending=r;continue
  lo=pending if fields[1].endswith(', Last>') else r
  pending=None
  yield lo,r,fields
letter=[];number=[]
for lo,hi,f in records('16.0.0'):
 if f[2].startswith('L'):letter.append((lo,hi))
 if f[2].startswith('N'):number.append((lo,hi))
def collapse(ranges):
 out=[]
 for lo,hi in ranges:
  if out and out[-1][1]+1==lo:out[-1]=(out[-1][0],hi)
  else:out.append((lo,hi))
 return out
ccc=[];decomp={}
for lo,hi,f in records('9.0.0'):
 if int(f[3]):ccc.extend((r,int(f[3])) for r in range(lo,hi+1))
 if f[5] and not f[5].startswith('<'):decomp[lo]=[int(x,16) for x in f[5].split()]
excluded=set()
for line in read('9.0.0','DerivedNormalizationProps.txt').splitlines():
 line=line.split('#')[0].strip()
 if not line:continue
 fields=[v.strip() for v in line.split(';')]
 if fields[1]!='Full_Composition_Exclusion':continue
 bounds=fields[0].split('..');lo=int(bounds[0],16);hi=int(bounds[-1],16)
 excluded.update(range(lo,hi+1))
compositions={tuple(parts):r for r,parts in decomp.items() if len(parts)==2 and r not in excluded}
lines=['// Code generated by internal/genunicode/generate.py. DO NOT EDIT.','// Unicode 16.0.0 categories; Unicode 9.0.0 NFC (HF tokenizers 0.22.2).','// See UNICODE-LICENSE.txt.','','package hftokenizer','']
for name,ranges in [('letterRanges',letter),('numberRanges',number)]:
 lines.append('var '+name+' = [...]runeRange{')
 lines.extend('\t{0x%x, 0x%x},'%(lo,hi) for lo,hi in collapse(ranges));lines.append('}\n')
lines.append('var combiningClasses = map[rune]uint8{')
lines.extend('\t0x%x: %d,'%(r,c) for r,c in ccc);lines.append('}\n')
lines.append('var canonicalDecompositions = map[rune][]rune{')
lines.extend('\t0x%x: {%s},'%(r,', '.join('0x%x'%p for p in parts)) for r,parts in sorted(decomp.items()));lines.append('}\n')
lines.append('var canonicalCompositions = map[[2]rune]rune{')
lines.extend('\t{0x%x, 0x%x}: 0x%x,'%(a,b,r) for (a,b),r in sorted(compositions.items()));lines.append('}\n')
(root/'unicode_tables.go').write_text('\n'.join(lines))
(root/'internal/genunicode/sources.json').write_text(json.dumps(manifest,indent=2)+'\n')
print('category ranges',len(collapse(letter))+len(collapse(number)),'CCC',len(ccc),'decompositions',len(decomp),'compositions',len(compositions))

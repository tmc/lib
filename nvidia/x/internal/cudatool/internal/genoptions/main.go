package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/tmc/lib/nvidia/x/internal/cudatool"
)

func main() {
	var (
		dataDir = flag.String("data", "optiondata", "directory containing optiondata text files")
		outFile = flag.String("out", "tables.gen.go", "output Go file")
		pkgName = flag.String("pkg", "cudatool", "package name")
	)
	flag.Parse()

	entries, err := os.ReadDir(*dataDir)
	if err != nil {
		log.Fatalf("genoptions: read data dir %s: %v", *dataDir, err)
	}

	type toolVersionData struct {
		tool    string
		version cudatool.Version
		options cudatool.Options
	}

	var allData []toolVersionData
	toolSet := make(map[string]bool)
	archByVersion := make(map[cudatool.Version][]string)
	allArchSet := make(map[string]bool)

	for _, e := range entries {
		if !strings.HasSuffix(e.Name(), ".txt") {
			continue
		}
		name := strings.TrimSuffix(e.Name(), ".txt")
		i := strings.LastIndex(name, "-")
		if i < 0 {
			continue
		}
		tool, verText := name[:i], name[i+1:]
		major, minor, ok := strings.Cut(verText, ".")
		if !ok {
			continue
		}
		var v cudatool.Version
		if _, err := fmt.Sscanf(major+" "+minor, "%d %d", &v.Major, &v.Minor); err != nil {
			log.Fatalf("genoptions: parse version in %s: %v", e.Name(), err)
		}

		b, err := os.ReadFile(filepath.Join(*dataDir, e.Name()))
		if err != nil {
			log.Fatalf("genoptions: read %s: %v", e.Name(), err)
		}

		opts, err := cudatool.ParseText(string(b))
		if err != nil {
			log.Fatalf("genoptions: parse %s: %v", e.Name(), err)
		}

		allData = append(allData, toolVersionData{
			tool:    tool,
			version: v,
			options: opts,
		})
		toolSet[tool] = true

		if tool == "nvcc" {
			if opt, ok := opts.Find("--gpu-architecture"); ok {
				for _, val := range opt.Values {
					if strings.HasPrefix(val, "compute_") || strings.HasPrefix(val, "sm_") || strings.HasPrefix(val, "lto_") {
						allArchSet[val] = true
						archByVersion[v] = append(archByVersion[v], val)
					}
				}
			}
		}
	}

	var tools []string
	for t := range toolSet {
		tools = append(tools, t)
	}
	sort.Strings(tools)

	var allArchs []string
	for a := range allArchSet {
		allArchs = append(allArchs, a)
	}
	sort.Strings(allArchs)

	byTool := make(map[string][]toolVersionData)
	for _, d := range allData {
		byTool[d.tool] = append(byTool[d.tool], d)
	}
	for _, list := range byTool {
		sort.Slice(list, func(i, j int) bool {
			return list[i].version.Compare(list[j].version) < 0
		})
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by genoptions from optiondata. DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package %s\n\n", *pkgName)

	// Tool name constants
	fmt.Fprintf(&buf, "// Known tool names recorded in optiondata.\n")
	fmt.Fprintf(&buf, "const (\n")
	for _, t := range tools {
		constName := "Tool" + toConstName(t)
		fmt.Fprintf(&buf, "\t%s = %q\n", constName, t)
	}
	fmt.Fprintf(&buf, ")\n\n")

	// Static corpus
	fmt.Fprintf(&buf, "var staticCorpus = map[string]*toolCorpus{\n")
	for _, t := range tools {
		list := byTool[t]
		fmt.Fprintf(&buf, "\t%q: {\n", t)
		fmt.Fprintf(&buf, "\t\tversions: []Version{\n")
		for _, d := range list {
			fmt.Fprintf(&buf, "\t\t\tV(%d, %d),\n", d.version.Major, d.version.Minor)
		}
		fmt.Fprintf(&buf, "\t\t},\n")
		fmt.Fprintf(&buf, "\t\toptions: map[Version]Options{\n")
		for _, d := range list {
			fmt.Fprintf(&buf, "\t\t\tV(%d, %d): {\n", d.version.Major, d.version.Minor)
			for _, opt := range d.options {
				arityStr := "Bare"
				if opt.Arity == cudatool.Value {
					arityStr = "Value"
				}
				fmt.Fprintf(&buf, "\t\t\t\t{Name: %q, Short: %q, Arity: %s, Default: %q",
					opt.Name, opt.Short, arityStr, opt.Default)
				if len(opt.Values) > 0 {
					fmt.Fprintf(&buf, ", Values: []string{")
					for vi, val := range opt.Values {
						if vi > 0 {
							fmt.Fprintf(&buf, ", ")
						}
						fmt.Fprintf(&buf, "%q", val)
					}
					fmt.Fprintf(&buf, "}")
				}
				fmt.Fprintf(&buf, "},\n")
			}
			fmt.Fprintf(&buf, "\t\t\t},\n")
		}
		fmt.Fprintf(&buf, "\t\t},\n")
		fmt.Fprintf(&buf, "\t},\n")
	}
	fmt.Fprintf(&buf, "}\n\n")

	// Known architectures
	fmt.Fprintf(&buf, "// KnownGPUArchitectures lists all unique GPU architectures (compute_*, sm_*, lto_*)\n")
	fmt.Fprintf(&buf, "// recorded across toolkits in optiondata, sorted.\n")
	fmt.Fprintf(&buf, "var KnownGPUArchitectures = []string{\n")
	for _, a := range allArchs {
		fmt.Fprintf(&buf, "\t%q,\n", a)
	}
	fmt.Fprintf(&buf, "}\n\n")

	// Supported architectures by version
	var archVersions []cudatool.Version
	for v := range archByVersion {
		archVersions = append(archVersions, v)
	}
	sort.Slice(archVersions, func(i, j int) bool { return archVersions[i].Compare(archVersions[j]) < 0 })

	fmt.Fprintf(&buf, "var staticSupportedArchitectures = map[Version][]string{\n")
	for _, v := range archVersions {
		archs := archByVersion[v]
		sort.Strings(archs)
		fmt.Fprintf(&buf, "\tV(%d, %d): {\n", v.Major, v.Minor)
		for _, a := range archs {
			fmt.Fprintf(&buf, "\t\t%q,\n", a)
		}
		fmt.Fprintf(&buf, "\t},\n")
	}
	fmt.Fprintf(&buf, "}\n\n")

	fmt.Fprintf(&buf, "// SupportedArchitectures returns the GPU architectures recorded for the given toolkit version.\n")
	fmt.Fprintf(&buf, "func SupportedArchitectures(v Version) []string {\n")
	fmt.Fprintf(&buf, "\tif archs, ok := staticSupportedArchitectures[v]; ok {\n")
	fmt.Fprintf(&buf, "\t\treturn append([]string(nil), archs...)\n")
	fmt.Fprintf(&buf, "\t}\n")
	fmt.Fprintf(&buf, "\tvar best Version\n")
	fmt.Fprintf(&buf, "\tfor known := range staticSupportedArchitectures {\n")
	fmt.Fprintf(&buf, "\t\tif known.Compare(v) <= 0 && known.Compare(best) > 0 {\n")
	fmt.Fprintf(&buf, "\t\t\tbest = known\n")
	fmt.Fprintf(&buf, "\t\t}\n")
	fmt.Fprintf(&buf, "\t}\n")
	fmt.Fprintf(&buf, "\tif best.Valid() {\n")
	fmt.Fprintf(&buf, "\t\treturn append([]string(nil), staticSupportedArchitectures[best]...)\n")
	fmt.Fprintf(&buf, "\t}\n")
	fmt.Fprintf(&buf, "\treturn nil\n")
	fmt.Fprintf(&buf, "}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatalf("genoptions: format output: %v\ncode:\n%s", err, buf.String())
	}

	if err := os.WriteFile(*outFile, formatted, 0o644); err != nil {
		log.Fatalf("genoptions: write %s: %v", *outFile, err)
	}
}

func toConstName(tool string) string {
	parts := strings.Split(tool, "-")
	for i, p := range parts {
		switch strings.ToLower(p) {
		case "nvcc":
			parts[i] = "NVCC"
		case "ptxas":
			parts[i] = "PTXAS"
		case "nvdisasm":
			parts[i] = "NVDisasm"
		case "cuobjdump":
			parts[i] = "CUObjDump"
		case "nvlink":
			parts[i] = "NVLink"
		case "nvprune":
			parts[i] = "NVPrune"
		default:
			if len(p) > 0 {
				parts[i] = strings.ToUpper(p[:1]) + p[1:]
			}
		}
	}
	return strings.Join(parts, "")
}

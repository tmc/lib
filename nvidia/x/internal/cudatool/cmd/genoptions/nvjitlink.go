package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"strings"

	"github.com/tmc/lib/nvidia/x/internal/cudatool"
)

// generateNVJITLinkFlags uses the nvJitLink option inventory, which differs
// from the nvlink command line inventory.
func generateNVJITLinkFlags(outFile, pkg string, data []toolVersionData) {
	var options cudatool.Options
	var version cudatool.Version
	for _, d := range data {
		if d.tool == "nvjitlink" && d.version.Compare(version) > 0 {
			options, version = d.options, d.version
		}
	}
	if len(options) == 0 {
		log.Fatal("genoptions: no nvjitlink optiondata")
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by genoptions from nvjitlink-%d.%d.txt. DO NOT EDIT.\n\n", version.Major, version.Minor)
	fmt.Fprintf(&b, "package %s\n\nimport (\"fmt\"; \"strconv\"; \"strings\")\n\n", pkg)
	fmt.Fprintln(&b, "// nvJitLink option names. Values are passed as -name=value.")
	fmt.Fprintln(&b, "const (")
	for _, opt := range options {
		name := strings.TrimLeft(opt.Name, "-")
		constant := toConstName(name)
		switch name {
		case "lto":
			constant = "LTO"
		case "ptx":
			constant = "PTX"
		case "Xptxas":
			constant = "XPTXAS"
		}
		fmt.Fprintf(&b, "Flag%s = %q\n", constant, opt.Name)
	}
	fmt.Fprintln(&b, ")")
	fmt.Fprintln(&b, "var optionArity = map[string]bool{ // true means a value is required")
	for _, opt := range options {
		fmt.Fprintf(&b, "%q: %t,\n", opt.Name, opt.Arity == cudatool.Value)
	}
	fmt.Fprintln(&b, "}")
	b.WriteString(`// ValidateOption checks a documented nvJitLink option before native linking.
func ValidateOption(flag string) error {
	if flag == "" || strings.ContainsRune(flag, 0) { return fmt.Errorf("nvjitlink: invalid option %q", flag) }
	name, value, hasValue := strings.Cut(flag, "=")
	wantValue, ok := optionArity[name]
	if !ok { return fmt.Errorf("nvjitlink: unknown option %q", name) }
	if wantValue != hasValue || wantValue && value == "" { return fmt.Errorf("nvjitlink: invalid value for %q", name) }
	if !wantValue { return nil }
	switch name {
	case FlagArch:
		arch := strings.TrimPrefix(strings.TrimPrefix(value, "sm_"), "compute_")
		if arch == value || len(arch) < 2 || len(arch) > 4 { return fmt.Errorf("nvjitlink: invalid architecture %q", value) }
		for i, ch := range arch {
			if ch >= '0' && ch <= '9' { continue }
			if i == len(arch)-1 && (ch == 'a' || ch == 'f') { continue }
			return fmt.Errorf("nvjitlink: invalid architecture %q", value)
		}
	case FlagMaxrregcount, FlagSplitCompile, FlagSplitCompileExtended, FlagJumpTableDensity:
		n, err := strconv.Atoi(value)
		if err != nil || n < 0 || name == FlagJumpTableDensity && n > 101 { return fmt.Errorf("nvjitlink: invalid value %q for %s", value, name) }
	case FlagFtz, FlagPrecDiv, FlagPrecSqrt, FlagFma:
		if value != "0" && value != "1" { return fmt.Errorf("nvjitlink: invalid value %q for %s", value, name) }
	}
	return nil
}`)
	formatted, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("genoptions: format nvjitlink flags: %v", err)
	}
	if err := writeGenerated(outFile, formatted); err != nil {
		log.Fatalf("genoptions: %v", err)
	}
}

func generateNvrtcFlags(outFile, pkg string, allData []toolVersionData) {
	// Find the latest nvcc options from allData to verify / enrich our specs
	var latest cudatool.Options
	var latestVer cudatool.Version
	for _, d := range allData {
		if d.tool == "nvcc" && d.version.Compare(latestVer) > 0 {
			latest = d.options
			latestVer = d.version
		}
	}

	// Enrich from latest nvcc optiondata if available
	specs := append([]nvrtcOptionSpec(nil), nvrtcKnownOptions...)
	for i, spec := range specs {
		if opt, ok := latest.Find(spec.Name); ok {
			if len(opt.Values) > 0 && len(spec.Values) == 0 {
				specs[i].Values = opt.Values
			}
			if opt.Default != "" && spec.Default == "" {
				specs[i].Default = opt.Default
			}
			if opt.Short != "" && spec.Short == "" {
				specs[i].Short = opt.Short
			}
		}
	}

	var buf bytes.Buffer
	fmt.Fprintf(&buf, "// Code generated by genoptions from optiondata. DO NOT EDIT.\n\n")
	fmt.Fprintf(&buf, "package %s\n\n", pkg)
	fmt.Fprintf(&buf, "import (\n\t\"fmt\"\n\t\"strings\"\n)\n\n")

	// Standard flag constants
	fmt.Fprintf(&buf, "// Standard compiler flag constants accepted by NVRTC.\n")
	fmt.Fprintf(&buf, "const (\n")
	fmt.Fprintf(&buf, "\tFlagGpuArchitecture               = %q\n", "--gpu-architecture")
	fmt.Fprintf(&buf, "\tFlagStd                           = %q\n", "-std")
	fmt.Fprintf(&buf, "\tFlagUseFastMath                   = %q\n", "--use_fast_math")
	fmt.Fprintf(&buf, "\tFlagFtz                           = %q\n", "-ftz")
	fmt.Fprintf(&buf, "\tFlagPrecDiv                       = %q\n", "-prec-div")
	fmt.Fprintf(&buf, "\tFlagPrecSqrt                      = %q\n", "-prec-sqrt")
	fmt.Fprintf(&buf, "\tFlagFmad                          = %q\n", "-fmad")
	fmt.Fprintf(&buf, "\tFlagDeviceAsDefaultExecutionSpace = %q\n", "--device-as-default-execution-space")
	fmt.Fprintf(&buf, "\tFlagDeviceDebug                   = %q\n", "--device-debug")
	fmt.Fprintf(&buf, "\tFlagGenerateLineInfo              = %q\n", "--generate-line-info")
	fmt.Fprintf(&buf, "\tFlagRelocatableDeviceCode         = %q\n", "--relocatable-device-code")
	fmt.Fprintf(&buf, "\tFlagMaxrregcount                  = %q\n", "--maxrregcount")
	fmt.Fprintf(&buf, "\tFlagExtraDeviceVectorization      = %q\n", "--extra-device-vectorization")
	fmt.Fprintf(&buf, "\tFlagDisableWarnings               = %q\n", "-w")
	fmt.Fprintf(&buf, "\tFlagWarningAsError                = %q\n", "--warning-as-error")
	fmt.Fprintf(&buf, "\tFlagIncludePath                   = %q\n", "--include-path")
	fmt.Fprintf(&buf, "\tFlagDefineMacro                   = %q\n", "-D")
	fmt.Fprintf(&buf, "\tFlagUndefineMacro                 = %q\n", "-U")
	fmt.Fprintf(&buf, "\tFlagPreInclude                    = %q\n", "--pre-include")
	fmt.Fprintf(&buf, "\tFlagDLTO                          = %q\n", "-dlto")
	fmt.Fprintf(&buf, "\tFlagTileOnly                      = %q\n", "--tile-only")
	fmt.Fprintf(&buf, "\tFlagEnableTile                    = %q\n", "--enable-tile")
	fmt.Fprintf(&buf, "\tFlagOptiXIR                       = %q\n", "--optix-ir")
	fmt.Fprintf(&buf, "\tFlagPCH                           = %q\n", "-pch")
	fmt.Fprintf(&buf, "\tFlagCreatePCH                     = %q\n", "--create-pch")
	fmt.Fprintf(&buf, "\tFlagUsePCH                        = %q\n", "--use-pch")
	fmt.Fprintf(&buf, "\tFlagOfastCompile                  = %q\n", "--Ofast-compile")
	fmt.Fprintf(&buf, "\tFlagRandomSeed                    = %q\n", "--frandom-seed")
	fmt.Fprintf(&buf, "\tFlagExtensibleWholeProgram        = %q\n", "--extensible-whole-program")
	fmt.Fprintf(&buf, "\tFlagDeviceStackProtector          = %q\n", "--device-stack-protector")
	fmt.Fprintf(&buf, "\tFlagTime                          = %q\n", "--time")
	fmt.Fprintf(&buf, "\tFlagNoCache                       = %q\n", "--no-cache")
	fmt.Fprintf(&buf, ")\n\n")

	// Standard C++ standards
	fmt.Fprintf(&buf, "// C++ language standards accepted by NVRTC -std flag.\n")
	fmt.Fprintf(&buf, "const (\n")
	fmt.Fprintf(&buf, "\tStdCXX03 = %q\n", "c++03")
	fmt.Fprintf(&buf, "\tStdCXX11 = %q\n", "c++11")
	fmt.Fprintf(&buf, "\tStdCXX14 = %q\n", "c++14")
	fmt.Fprintf(&buf, "\tStdCXX17 = %q\n", "c++17")
	fmt.Fprintf(&buf, "\tStdCXX20 = %q\n", "c++20")
	fmt.Fprintf(&buf, "\tStdCXX23 = %q\n", "c++23")
	fmt.Fprintf(&buf, ")\n\n")

	// Fast compile levels
	fmt.Fprintf(&buf, "// Fast compilation levels accepted by NVRTC --Ofast-compile flag.\n")
	fmt.Fprintf(&buf, "const (\n")
	fmt.Fprintf(&buf, "\tFastCompile0   = %q\n", "0")
	fmt.Fprintf(&buf, "\tFastCompileMin = %q\n", "min")
	fmt.Fprintf(&buf, "\tFastCompileMid = %q\n", "mid")
	fmt.Fprintf(&buf, "\tFastCompileMax = %q\n", "max")
	fmt.Fprintf(&buf, ")\n\n")

	// Compute & SM arch helpers
	fmt.Fprintf(&buf, "// ComputeArch returns the virtual compute architecture string for major.minor\n")
	fmt.Fprintf(&buf, "// (e.g., \"compute_80\" for 8, 0).\n")
	fmt.Fprintf(&buf, "func ComputeArch(major, minor int) string {\n")
	fmt.Fprintf(&buf, "\treturn fmt.Sprintf(\"compute_%%d%%d\", major, minor)\n")
	fmt.Fprintf(&buf, "}\n\n")

	fmt.Fprintf(&buf, "// SmArch returns the physical GPU architecture string for major.minor\n")
	fmt.Fprintf(&buf, "// (e.g., \"sm_80\" for 8, 0).\n")
	fmt.Fprintf(&buf, "func SmArch(major, minor int) string {\n")
	fmt.Fprintf(&buf, "\treturn fmt.Sprintf(\"sm_%%d%%d\", major, minor)\n")
	fmt.Fprintf(&buf, "}\n\n")

	// OptionDef struct and slice
	fmt.Fprintf(&buf, "// OptionDef describes a compiler option recognized by NVRTC.\n")
	fmt.Fprintf(&buf, "type OptionDef struct {\n")
	fmt.Fprintf(&buf, "\tName    string\n")
	fmt.Fprintf(&buf, "\tShort   string\n")
	fmt.Fprintf(&buf, "\tArity   string // \"bare\" or \"value\"\n")
	fmt.Fprintf(&buf, "\tDefault string\n")
	fmt.Fprintf(&buf, "\tValues  []string\n")
	fmt.Fprintf(&buf, "}\n\n")

	fmt.Fprintf(&buf, "// SupportedOptions records all compiler options recognized by NVRTC.\n")
	fmt.Fprintf(&buf, "var SupportedOptions = []OptionDef{\n")
	for _, spec := range specs {
		fmt.Fprintf(&buf, "\t{Name: %q, Short: %q, Arity: %q, Default: %q",
			spec.Name, spec.Short, spec.Arity, spec.Default)
		if len(spec.Values) > 0 {
			fmt.Fprintf(&buf, ", Values: []string{")
			for vi, val := range spec.Values {
				if vi > 0 {
					fmt.Fprintf(&buf, ", ")
				}
				fmt.Fprintf(&buf, "%q", val)
			}
			fmt.Fprintf(&buf, "}")
		}
		fmt.Fprintf(&buf, "},\n")
	}
	fmt.Fprintf(&buf, "}\n\n")

	// Option lookup
	fmt.Fprintf(&buf, "func findOption(name string) (OptionDef, bool) {\n")
	fmt.Fprintf(&buf, "\tfor _, opt := range SupportedOptions {\n")
	fmt.Fprintf(&buf, "\t\tif opt.Name == name || (opt.Short != \"\" && opt.Short == name) {\n")
	fmt.Fprintf(&buf, "\t\t\treturn opt, true\n")
	fmt.Fprintf(&buf, "\t\t}\n")
	fmt.Fprintf(&buf, "\t}\n")
	fmt.Fprintf(&buf, "\treturn OptionDef{}, false\n")
	fmt.Fprintf(&buf, "}\n\n")

	// ValidateOption
	fmt.Fprintf(&buf, "// ValidateOption checks if flag is a recognized NVRTC option and validates its value if constrained.\n")
	fmt.Fprintf(&buf, "func ValidateOption(flag string) error {\n")
	fmt.Fprintf(&buf, "\tif flag == \"\" {\n\t\treturn fmt.Errorf(\"nvrtc: empty option\")\n\t}\n")
	fmt.Fprintf(&buf, "\tif strings.ContainsRune(flag, 0) {\n\t\treturn fmt.Errorf(\"nvrtc: option contains NUL\")\n\t}\n")
	fmt.Fprintf(&buf, "\tif flag == \"-O0\" || flag == \"-O1\" || flag == \"-O2\" || flag == \"-O3\" {\n\t\treturn nil\n\t}\n")
	fmt.Fprintf(&buf, "\tif strings.HasPrefix(flag, \"-D\") || strings.HasPrefix(flag, \"-U\") || strings.HasPrefix(flag, \"-I\") {\n")
	fmt.Fprintf(&buf, "\t\tif len(flag) > 2 {\n\t\t\treturn nil\n\t\t}\n\t}\n")
	fmt.Fprintf(&buf, "\tname, val, hasVal := strings.Cut(flag, \"=\")\n")
	fmt.Fprintf(&buf, "\topt, ok := findOption(name)\n")
	fmt.Fprintf(&buf, "\tif !ok {\n\t\treturn fmt.Errorf(\"nvrtc: unknown option %%q\", flag)\n\t}\n")
	fmt.Fprintf(&buf, "\tif opt.Arity == \"bare\" && hasVal {\n")
	fmt.Fprintf(&buf, "\t\treturn fmt.Errorf(\"nvrtc: option %%q takes no argument, given %%q\", name, val)\n\t}\n")
	fmt.Fprintf(&buf, "\tif opt.Arity == \"value\" && !hasVal {\n")
	fmt.Fprintf(&buf, "\t\treturn fmt.Errorf(\"nvrtc: option %%q requires an argument (=value)\", name)\n\t}\n")
	fmt.Fprintf(&buf, "\tif len(opt.Values) > 0 {\n")
	fmt.Fprintf(&buf, "\t\tfound := false\n")
	fmt.Fprintf(&buf, "\t\tfor _, v := range opt.Values {\n")
	fmt.Fprintf(&buf, "\t\t\tif v == val {\n\t\t\t\tfound = true\n\t\t\t\tbreak\n\t\t\t}\n")
	fmt.Fprintf(&buf, "\t\t}\n")
	fmt.Fprintf(&buf, "\t\tif !found {\n")
	fmt.Fprintf(&buf, "\t\t\treturn fmt.Errorf(\"nvrtc: invalid value %%q for option %%q (allowed: %%s)\", val, name, strings.Join(opt.Values, \", \"))\n")
	fmt.Fprintf(&buf, "\t\t}\n\t}\n")
	fmt.Fprintf(&buf, "\tif name == \"--gpu-architecture\" || name == \"-arch\" {\n")
	fmt.Fprintf(&buf, "\t\tif !strings.HasPrefix(val, \"compute_\") && !strings.HasPrefix(val, \"sm_\") && !strings.HasPrefix(val, \"lto_\") {\n")
	fmt.Fprintf(&buf, "\t\t\treturn fmt.Errorf(\"nvrtc: invalid architecture %%q (expected compute_*, sm_*, or lto_*)\", val)\n")
	fmt.Fprintf(&buf, "\t\t}\n\t}\n")
	fmt.Fprintf(&buf, "\treturn nil\n")
	fmt.Fprintf(&buf, "}\n")

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatalf("genoptions: format output: %v\ncode:\n%s", err, buf.String())
	}

	if err := os.WriteFile(outFile, formatted, 0o644); err != nil {
		log.Fatalf("genoptions: write %s: %v", outFile, err)
	}
}

func toConstName(tool string) string {
	parts := strings.Split(tool, "-")
	for i, p := range parts {
		switch strings.ToLower(p) {
		case "nvcc":
			parts[i] = "NVCC"
		case "ptxas":
			parts[i] = "PTXAS"
		case "nvdisasm":
			parts[i] = "NVDisasm"
		case "cuobjdump":
			parts[i] = "CUObjDump"
		case "nvlink":
			parts[i] = "NVLink"
		case "nvprune":
			parts[i] = "NVPrune"
		default:
			if len(p) > 0 {
				parts[i] = strings.ToUpper(p[:1]) + p[1:]
			}
		}
	}
	return strings.Join(parts, "")
}

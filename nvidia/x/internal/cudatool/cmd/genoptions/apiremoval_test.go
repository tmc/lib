package main

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

func TestWriteGeneratedRefusesAPIRemoval(t *testing.T) {
	const header = "// Code generated by genoptions. DO NOT EDIT.\n\npackage p\n\n"
	tests := []struct {
		name  string
		old   string
		new   string
		allow bool
		want  string // substring of the refusal, or "" to expect a write
	}{
		{
			name: "unchanged",
			old:  "const A = 1\n",
			new:  "const A = 1\n",
		},
		{
			name: "added",
			old:  "const A = 1\n",
			new:  "const A = 1\nconst B = 2\n",
		},
		{
			name: "removed const",
			old:  "const A = 1\nconst B = 2\n",
			new:  "const A = 1\n",
			want: "B",
		},
		{
			name: "renamed type is a removal",
			old:  "type Option struct{}\n",
			new:  "type OptionLegacy struct{}\n",
			want: "Option",
		},
		{
			name: "removed method",
			old:  "type T struct{}\n\nfunc (t T) Validate() {}\n",
			new:  "type T struct{}\n",
			want: "T.Validate",
		},
		{
			name: "unexported removal is not an API change",
			old:  "const a = 1\nconst b = 2\n",
			new:  "const a = 1\n",
		},
		{
			name:  "allowed",
			old:   "const A = 1\nconst B = 2\n",
			new:   "const A = 1\n",
			allow: true,
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			file := filepath.Join(t.TempDir(), "flags.gen.go")
			if err := os.WriteFile(file, []byte(header+tt.old), 0o644); err != nil {
				t.Fatal(err)
			}
			defer func(prev bool) { *allowAPIRemoval = prev }(*allowAPIRemoval)
			*allowAPIRemoval = tt.allow

			err := writeGenerated(file, []byte(header+tt.new))
			got, readErr := os.ReadFile(file)
			if readErr != nil {
				t.Fatal(readErr)
			}
			if tt.want == "" {
				if err != nil {
					t.Fatalf("writeGenerated: %v", err)
				}
				if string(got) != header+tt.new {
					t.Errorf("file not replaced:\n%s", got)
				}
				return
			}
			if err == nil {
				t.Fatalf("writeGenerated succeeded, want refusal naming %s", tt.want)
			}
			if !strings.Contains(err.Error(), tt.want) {
				t.Errorf("refusal does not name %s: %v", tt.want, err)
			}
			if string(got) != header+tt.old {
				t.Errorf("refused but wrote anyway:\n%s", got)
			}
		})
	}
}

func TestWriteGeneratedCreatesMissingFile(t *testing.T) {
	file := filepath.Join(t.TempDir(), "flags.gen.go")
	src := []byte("package p\n\nconst A = 1\n")
	if err := writeGenerated(file, src); err != nil {
		t.Fatalf("writeGenerated: %v", err)
	}
	got, err := os.ReadFile(file)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != string(src) {
		t.Errorf("got %q, want %q", got, src)
	}
}

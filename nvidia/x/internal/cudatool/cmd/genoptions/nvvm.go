package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
)

func generateNVVMFlags(outFile, pkg string) {
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by genoptions from nvvm.h. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\nimport (\n\t\"fmt\"\n\t\"strconv\"\n\t\"strings\"\n)\n\n", pkg)
	fmt.Fprintln(&b, "// Standard compiler flag constants accepted by NVVM.")
	fmt.Fprintln(&b, "const (")
	fmt.Fprintf(&b, "\tFlagG                = \"-g\"\n")
	fmt.Fprintf(&b, "\tFlagOpt              = \"-opt\"\n")
	fmt.Fprintf(&b, "\tFlagArch             = \"-arch\"\n")
	fmt.Fprintf(&b, "\tFlagFtz              = \"-ftz\"\n")
	fmt.Fprintf(&b, "\tFlagPrecSqrt         = \"-prec-sqrt\"\n")
	fmt.Fprintf(&b, "\tFlagPrecDiv          = \"-prec-div\"\n")
	fmt.Fprintf(&b, "\tFlagFma              = \"-fma\"\n")
	fmt.Fprintf(&b, "\tFlagJumpTableDensity = \"-jump-table-density\"\n")
	fmt.Fprintf(&b, "\tFlagGenLTO           = \"-gen-lto\"\n")
	fmt.Fprintln(&b, ")")
	fmt.Fprintln(&b, "")
	fmt.Fprintln(&b, "var optionArity = map[string]bool{ // true means a value (=value) is required")
	fmt.Fprintf(&b, "\t\"-g\":                  false,\n")
	fmt.Fprintf(&b, "\t\"-opt\":                true,\n")
	fmt.Fprintf(&b, "\t\"-arch\":               true,\n")
	fmt.Fprintf(&b, "\t\"-ftz\":                true,\n")
	fmt.Fprintf(&b, "\t\"-prec-sqrt\":          true,\n")
	fmt.Fprintf(&b, "\t\"-prec-div\":           true,\n")
	fmt.Fprintf(&b, "\t\"-fma\":                true,\n")
	fmt.Fprintf(&b, "\t\"-jump-table-density\": true,\n")
	fmt.Fprintf(&b, "\t\"-gen-lto\":            false,\n")
	fmt.Fprintln(&b, "}")
	fmt.Fprintln(&b, "")
	fmt.Fprintf(&b, "// ComputeArch returns the virtual compute architecture string for major.minor\n")
	fmt.Fprintf(&b, "// (e.g., \"compute_80\" for 8, 0).\n")
	fmt.Fprintf(&b, "func ComputeArch(major, minor int) string {\n")
	fmt.Fprintf(&b, "\treturn fmt.Sprintf(\"compute_%%d%%d\", major, minor)\n")
	fmt.Fprintf(&b, "}\n\n")
	b.WriteString(`// ValidateOption checks a documented NVVM compiler option before native compilation.
func ValidateOption(flag string) error {
	if flag == "" || strings.ContainsRune(flag, 0) {
		return fmt.Errorf("nvvm: invalid option %q", flag)
	}
	name, value, hasValue := strings.Cut(flag, "=")
	wantValue, ok := optionArity[name]
	if !ok {
		return fmt.Errorf("nvvm: unknown option %q", name)
	}
	if wantValue != hasValue || (wantValue && value == "") {
		if wantValue {
			return fmt.Errorf("nvvm: option %q requires an argument (=value)", name)
		}
		return fmt.Errorf("nvvm: option %q takes no argument, given %q", name, value)
	}
	if !wantValue {
		return nil
	}
	switch name {
	case FlagArch:
		if !strings.HasPrefix(value, "compute_") {
			return fmt.Errorf("nvvm: invalid architecture %q (expected compute_*)", value)
		}
		arch := strings.TrimPrefix(value, "compute_")
		if len(arch) < 2 || len(arch) > 5 {
			return fmt.Errorf("nvvm: invalid architecture %q", value)
		}
		for i, ch := range arch {
			if ch >= '0' && ch <= '9' {
				continue
			}
			if i == len(arch)-1 && (ch == 'a' || ch == 'f') {
				continue
			}
			return fmt.Errorf("nvvm: invalid architecture %q", value)
		}
	case FlagOpt:
		if value != "0" && value != "3" {
			return fmt.Errorf("nvvm: invalid value %q for %s (must be 0 or 3)", value, name)
		}
	case FlagFtz, FlagPrecSqrt, FlagPrecDiv, FlagFma:
		if value != "0" && value != "1" {
			return fmt.Errorf("nvvm: invalid value %q for %s (must be 0 or 1)", value, name)
		}
	case FlagJumpTableDensity:
		n, err := strconv.Atoi(value)
		if err != nil || n < 0 || n > 101 {
			return fmt.Errorf("nvvm: invalid value %q for %s (must be 0-101)", value, name)
		}
	}
	return nil
}
`)

	formatted, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("genoptions: format nvvm flags: %v", err)
	}
	if err := writeGenerated(outFile, formatted); err != nil {
		log.Fatalf("genoptions: %v", err)
	}
}

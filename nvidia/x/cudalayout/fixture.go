package cudalayout

import "fmt"

const (
	TargetSM100a = "sm_100a"
	TargetSM103a = "sm_103a"
	TargetSM107a = "sm_107a"
	TargetSM100f = "sm_100f"
	TargetSM103f = "sm_103f"
	TargetSM107f = "sm_107f"
	TargetSM121a = "sm_121a"
)

// FixtureSource emits a small CUDA source fixture consuming a physical tile.
// It is syntax-only until compiled by an explicitly authorized native gate.
func FixtureSource(t Tile) (string, error) { return FixtureSourceForTarget(t, TargetSM100a) }

// FixtureSourceForTarget emits a checked consumer fixture for an admitted
// target. The kernel uses row stride and the same bounded XOR swizzle as Index.
func FixtureSourceForTarget(t Tile, target string) (string, error) {
	if _, err := t.FootprintBytes(); err != nil {
		return "", err
	}
	switch target {
	case TargetSM100a, TargetSM103a, TargetSM107a, TargetSM100f, TargetSM103f, TargetSM107f, TargetSM121a:
	default:
		return "", fmt.Errorf("%w: no fixture for target %q", ErrUnmodeled, target)
	}
	typeName := map[int]string{1: "unsigned char", 2: "half", 4: "float"}[t.elemBytes]
	include := ""
	if t.elemBytes == 2 {
		include = "#include <cuda_fp16.h>\n"
	}
	return fmt.Sprintf(`// generated by cudalayout/v1 target=%s
// rows=%d cols=%d stride_elements=%d element_bytes=%d swizzle=%s
// Software XOR permutation; no vendor TMA mapping is implied.
%s
extern "C" __global__ void layout_copy(const %s* in, %s* out) {
  unsigned long long i = (unsigned long long)blockIdx.x * blockDim.x + threadIdx.x;
  if (i < %dULL) {
    unsigned long long row=i/%dULL, col=i%%%dULL;
    unsigned long long byte_col=col*%dULL;
    unsigned long long sw=%dULL ? ((row*%dULL)&%dULL) : 0ULL;
    unsigned long long byte_offset=row*%dULL+(byte_col^sw);
    out[byte_offset/%dULL] = in[i];
  }
}
// identity=%s
`, target, t.rows, t.cols, t.stride, t.elemBytes, t.swizzle, include, typeName, typeName, t.rows*t.cols, t.cols, t.cols, t.elemBytes, t.swizzle, t.elemBytes, max(0, int(t.swizzle)-1), t.stride*t.elemBytes, t.elemBytes, t.Identity()), nil
}

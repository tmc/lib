// Package cudair provides a typed Intermediate Representation (IR) graph, immutable validated
// snapshots, and waterfall memory arena planning for GPU tensor graphs.
//
// # Graph Representation
//
// Computation graphs are constructed from an authoritative operation set: Input, Constant, Add,
// Multiply, Sub, Div, Neg, Exp, Log, Sqrt, Relu, Gelu, Matmul, ReduceSum, ReduceMax, Reshape,
// Transpose, Slice, and Concat.
//
// Every node carries explicit metadata including [DataType], shape extents, [cudashape.Layout],
// strides, and storage effects ([StorageEffect]).
//
// # Immutable Validated Snapshots
//
// A mutable [Graph] can be frozen and validated using [Graph.Snapshot]. Validation ensures:
//   - The graph is a directed acyclic graph (no cycles).
//   - Nodes have unmixed single-graph ownership (cross-graph inputs are rejected).
//   - All operations conform to the authoritative semantic registry.
//   - Shapes, ranks, reduction axes, permutations, and dtypes are strictly compatible.
//   - Graph outputs are valid and reachable.
//
// # Arena Allocation Planning
//
// The [PlanMemory] function calculates tensor live ranges and overlays non-overlapping intermediate
// tensor buffers into a single contiguous device memory scratchpad, minimizing GPU VRAM allocations
// while respecting storage aliases and memory limits.
//
// This package is outside the compatibility promise of
// github.com/tmc/lib/nvidia. Its API may change or be removed in patch releases.
//
// # Device-Function Emission
//
// Nodes implementing [Emitter] can render themselves as self-contained CUDA `__device__` functions
// using [EmitFromBody] and compose into trees with [EmitTree]. [CompositeEmitter] represents
// sequential composition: each child's output width must equal the next child's input width.
// Emission is opt-in and fail-closed: nodes without emission support fail with
// [ErrEmissionUnsupported], and backward emission requires explicit [BackwardEmitter] support
// failing with [ErrBackwardEmissionUnsupported].
//
// Emitted functions must use the signatures generated by [EmitFromBody] and [EmitBackwardFromBody].
// Their bodies are tokenized and fail closed on preprocessor directives, token pasting, line
// continuations, unsupported calls, and writes outside supported body-local values or generated
// backward gradient outputs. Forward context is available only through the generated `__cudair_ctx`
// byte accessors, which check every offset against [Emitter.FwdCtxBytes]. Integer constant offsets
// are checked at emission; dynamic offsets are checked at run time. A parent may pass its context
// to a generated child only with the exact context expression selected by [EmitTree].
//
// Divergence from tiny-cuda-nn: in tiny-cuda-nn, adjacent-width disagreements are deferred to C++
// template instantiation at NVRTC compile time, producing verbose template errors. In cudair,
// [EmitTree] checks adjacent input/output widths eagerly in Go, returning a clear Go error
// identifying both nodes and their mismatched widths before invoking NVRTC. This is deliberate:
// unlike tiny-cuda-nn, width errors are reported before compilation.

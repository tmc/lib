// Command cuben generates type-safe Go wrappers from CUDA kernel declarations.
//
// Usage:
//
//	cuben -package mypkg -input kernels.cu -output kernels.gen.go
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"regexp"
	"strings"
)

var (
	flagPkg    = flag.String("package", "main", "Go package name")
	flagInput  = flag.String("input", "", "Path to CUDA .cu source file")
	flagOutput = flag.String("output", "", "Output Go file path (default stdout)")
)

// KernelDef represents an extracted __global__ kernel declaration.
type KernelDef struct {
	Name   string
	Params []ParamDef
}

// ParamDef represents a single kernel parameter.
type ParamDef struct {
	Name string
	Type string
}

var kernelRegex = regexp.MustCompile(`extern\s+"C"\s+__global__\s+void\s+(\w+)\s*\(([^)]*)\)`)

func parseCUDA(src string) ([]KernelDef, error) {
	matches := kernelRegex.FindAllStringSubmatch(src, -1)
	var kernels []KernelDef

	for _, m := range matches {
		kName := m[1]
		paramsRaw := strings.Split(m[2], ",")
		var params []ParamDef

		for _, p := range paramsRaw {
			p = strings.TrimSpace(p)
			if p == "" {
				continue
			}
			parts := strings.Fields(p)
			if len(parts) < 2 {
				continue
			}
			pName := parts[len(parts)-1]
			pType := strings.Join(parts[:len(parts)-1], " ")
			params = append(params, ParamDef{
				Name: pName,
				Type: pType,
			})
		}

		kernels = append(kernels, KernelDef{
			Name:   kName,
			Params: params,
		})
	}

	return kernels, nil
}

func mapTypeToGo(cudaType string) string {
	cudaType = strings.TrimSpace(cudaType)
	cudaType = strings.TrimPrefix(cudaType, "const ")
	cudaType = strings.TrimPrefix(cudaType, "volatile ")
	cudaType = strings.ReplaceAll(cudaType, "__restrict__", "")
	cudaType = strings.TrimSpace(cudaType)

	if strings.HasSuffix(cudaType, "*") {
		return "driver.DevicePtr"
	}

	switch cudaType {
	case "int", "int32_t":
		return "int32"
	case "unsigned int", "uint32_t":
		return "uint32"
	case "long long", "int64_t":
		return "int64"
	case "unsigned long long", "uint64_t":
		return "uint64"
	case "float":
		return "float32"
	case "double":
		return "float64"
	case "bool":
		return "bool"
	default:
		return "any"
	}
}

func generateGo(pkg string, kernels []KernelDef, sourceContent string) ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteString("// Code generated by cuben; DO NOT EDIT.\n\n")
	buf.WriteString("package " + pkg + "\n\n")
	buf.WriteString("import (\n")
	buf.WriteString("\t\"github.com/tmc/lib/nvidia/driver\"\n")
	buf.WriteString("\t\"github.com/tmc/lib/nvidia/x/cuda\"\n")
	buf.WriteString("\t\"github.com/tmc/lib/nvidia/x/cudalaunch\"\n")
	buf.WriteString(")\n\n")

	for _, k := range kernels {
		buf.WriteString(fmt.Sprintf("// Launch%s dispatches the %s CUDA kernel.\n", k.Name, k.Name))
		buf.WriteString(fmt.Sprintf("func Launch%s(stream *cuda.Stream, fn driver.Function, grid, block cudalaunch.Dim3, shmem uint32", k.Name))


		for _, p := range k.Params {
			goType := mapTypeToGo(p.Type)
			buf.WriteString(fmt.Sprintf(", %s %s", p.Name, goType))
		}
		buf.WriteString(") error {\n")
		buf.WriteString("\tl := cudalaunch.Kernel(fn).\n")
		buf.WriteString("\t\tGrid(grid.X, grid.Y, grid.Z).\n")
		buf.WriteString("\t\tBlock(block.X, block.Y, block.Z).\n")
		buf.WriteString("\t\tSharedMem(shmem).\n")
		buf.WriteString("\t\tOn(stream)\n\n")

		buf.WriteString("\treturn l.Launch(")
		for i, p := range k.Params {
			buf.WriteString(p.Name)
			if i < len(k.Params)-1 {
				buf.WriteString(", ")
			}
		}
		buf.WriteString(")\n}\n\n")
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return buf.Bytes(), nil // return unformatted on syntax error for inspection
	}
	return formatted, nil
}

func main() {
	flag.Parse()

	if *flagInput == "" {
		fmt.Fprintln(os.Stderr, "cuben: -input file required")
		os.Exit(1)
	}

	src, err := os.ReadFile(*flagInput)
	if err != nil {
		fmt.Fprintf(os.Stderr, "cuben: read input: %v\n", err)
		os.Exit(1)
	}

	kernels, err := parseCUDA(string(src))
	if err != nil {
		fmt.Fprintf(os.Stderr, "cuben: parse cuda: %v\n", err)
		os.Exit(1)
	}

	code, err := generateGo(*flagPkg, kernels, string(src))
	if err != nil {
		fmt.Fprintf(os.Stderr, "cuben: codegen: %v\n", err)
		os.Exit(1)
	}

	if *flagOutput != "" {
		if err := os.WriteFile(*flagOutput, code, 0644); err != nil {
			fmt.Fprintf(os.Stderr, "cuben: write output: %v\n", err)
			os.Exit(1)
		}
	} else {
		os.Stdout.Write(code)
	}
}

package nvrtcx

import (
	"errors"
	"fmt"
	"strings"
	"testing"

	"github.com/tmc/lib/nvidia/driver"
)

func TestPTXISA(t *testing.T) {
	tests := []struct {
		name, ptx, want string
	}{
		{"nvrtc", "//\n// Generated by NVIDIA NVVM Compiler\n//\n\n.version 9.4\n.target sm_121\n.address_size 64\n", "9.4"},
		{"indented", "\t.version 8.5 \n.target sm_90\n", "8.5"},
		{"crlf", ".version 9.0\r\n.target sm_121\r\n", "9.0"},
		{"comment", "// .version 1.0\n.version 9.1\n", "9.1"},
		{"missing", ".target sm_90\n.address_size 64\n", ""},
		{"bare", ".version\n", ""},
		{"empty", "", ""},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			if got := ptxISA(tt.ptx); got != tt.want {
				t.Errorf("ptxISA(%q) = %q, want %q", tt.ptx, got, tt.want)
			}
		})
	}
}

func TestUnsupportedPTXError(t *testing.T) {
	loadErr := fmt.Errorf("load: %w", driver.ErrUnsupportedPtxVersion)
	tests := []struct {
		name    string
		isa     string
		version int
		want    []string
	}{
		{"cuda13.0", "9.4", 13000, []string{"PTX .version 9.4", "CUDA 13.0 driver JIT", "WithDeviceArch"}},
		{"cuda12.8", "8.8", 12080, []string{"PTX .version 8.8", "CUDA 12.8 driver JIT"}},
		{"cuda13.4", "9.5", 13040, []string{"PTX .version 9.5", "CUDA 13.4 driver JIT"}},
		{"unknown driver", "9.4", 0, []string{"PTX .version 9.4", "too new for the driver JIT", "WithPhysicalArch"}},
		{"unknown isa", "", 13000, []string{"PTX .version unknown", "CUDA 13.0 driver JIT"}},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			err := unsupportedPTXError(tt.isa, tt.version, loadErr)
			if !errors.Is(err, driver.ErrUnsupportedPtxVersion) {
				t.Fatalf("errors.Is(%v, ErrUnsupportedPtxVersion) = false", err)
			}
			for _, s := range tt.want {
				if !strings.Contains(err.Error(), s) {
					t.Errorf("error %q does not contain %q", err, s)
				}
			}
		})
	}
}

func TestPTXVersionErrorOtherErrors(t *testing.T) {
	for _, err := range []error{driver.ErrInvalidPtx, fmt.Errorf("x: %w", driver.ErrNoBinaryForGpu)} {
		if got := ptxVersionError(".version 9.4\n", err); got != err {
			t.Errorf("ptxVersionError(%v) = %v, want unchanged", err, got)
		}
	}
	err := ptxVersionError(".version 9.4\n", driver.ErrUnsupportedPtxVersion)
	if !errors.Is(err, driver.ErrUnsupportedPtxVersion) || !strings.Contains(err.Error(), "PTX .version 9.4") {
		t.Errorf("ptxVersionError = %v", err)
	}
}

func q8CopyPlan(t *testing.T, size int64) *Plan {
	t.Helper()
	limits, err := LimitsFromDevice("sm_121a")
	if err != nil {
		t.Fatal(err)
	}
	p, err := NewPlan(limits)
	if err != nil {
		t.Fatal(err)
	}
	for _, r := range []Request{{Name: "padding", Size: 17, Alignment: 16, Dynamic: true}, {Name: "stage0", Size: size, Alignment: 32, Dynamic: true}} {
		if _, err := p.Add(r); err != nil {
			t.Fatal(err)
		}
	}
	return p
}


func TestStagedQ8CopyConsumer(t *testing.T) {
	raw := make([]byte, 6*34)
	for i := range raw {
		raw[i] = byte(i*37 + 19)
	}
	tensor, err := cudaprepack.RepackQ8_0(raw, 2, 96)
	if err != nil {
		t.Fatal(err)
	}
	padded := bytes.Repeat([]byte{0xed}, 224)
	for row := 0; row < 2; row++ {
		copy(padded[row*112:], tensor.Payload[row*96:row*96+96])
	}
	tensor.Payload = padded
	tensor.BoxDesc.GlobalStrides[0] = 112
	p := q8CopyPlan(t, 204)
	f, err := StagedQ8CopyFixture(p, tensor)
	if err != nil {
		t.Fatal(err)
	}
	if f.GridBlocks != 2 || f.BlockThreads != 128 || f.DynamicBytes != 236 || f.RawBytes != 204 || f.PrepackReadBytes != 204 || f.PrepackWriteBytes != 236 || f.WorkspaceBytes != 236 {
		t.Fatalf("wrong allocation or conversion costs: %+v", f)
	}
	if err := p.ValidateBase(16); err == nil {
		t.Fatal("unaligned base accepted")
	}
	for _, want := range []string{"__align__(32)", "raw + 32", "__syncthreads();", "if (i < 204)"} {
		if !strings.Contains(f.Source, want) {
			t.Fatalf("missing emitted contract %q", want)
		}
	}
	if strings.Count(f.Source, "if (i < 204)") != 2 || strings.Index(f.Source, "__syncthreads();") > strings.Index(f.Source, "out[i] =") {
		t.Fatal("copy tail or consumer barrier missing")
	}
	// Extract the emitted indexing constants. Interpret the bounded byte
	// accesses and barrier phases, comparing against original standard blocks.
	constant := func(pattern string) int {
		t.Helper()
		m := regexp.MustCompile(pattern).FindStringSubmatch(f.Source)
		if len(m) != 2 {
			t.Fatal("missing source indexing constant", pattern)
		}
		n, err := strconv.Atoi(m[1])
		if err != nil {
			t.Fatal(err)
		}
		return n
	}
	rowBlocks := constant(`block / (\d+)`)
	columnBlocks := constant(`block % (\d+)`)
	rowStride := constant(`payload\[row \* (\d+)`)
	out := bytes.Repeat([]byte{0xff}, len(raw))
	for block := 0; block < f.GridBlocks; block++ {
		tile := make([]byte, f.DynamicBytes)
		for thread := 0; thread < f.BlockThreads; thread++ {
			i := block*f.BlockThreads + thread
			if i >= len(raw) {
				continue
			}
			b, part := i/34, i%34
			if part < 2 {
				tile[32+thread] = tensor.Scales[b*2+part]
			} else {
				tile[32+thread] = tensor.Payload[(b/rowBlocks)*rowStride+(b%columnBlocks)*32+part-2]
			}
		}
		for thread := 0; thread < f.BlockThreads; thread++ {
			i := block*f.BlockThreads + thread
			if i < len(out) {
				out[i] = tile[32+thread]
			}
		}
	}
	if !bytes.Equal(out, raw) {
		t.Fatal("generated byte indices changed scale bits or payload tails")
	}
}

func TestStagedQ8CopyRefusals(t *testing.T) {
	tensor, err := cudaprepack.RepackQ8_0(make([]byte, 34), 1, 32)
	if err != nil {
		t.Fatal(err)
	}
	for _, tt := range []struct {
		name string
		plan *Plan
	}{
		{"nil", nil}, {"small", q8CopyPlan(t, 33)},
	} {
		t.Run(tt.name, func(t *testing.T) {
			if _, err := StagedQ8CopyFixture(tt.plan, tensor); err == nil {
				t.Fatal("invalid plan accepted")
			}
		})
	}
	for _, arch := range []string{"sm_100a", "sm_999a"} {
		t.Run(arch, func(t *testing.T) {
			copy := *tensor
			copy.Arch = arch
			if _, err := StagedQ8CopyFixture(q8CopyPlan(t, 34), &copy); err == nil {
				t.Fatal("unprobed or unsupported target accepted")
			}
		})
	}
	p, err := NewPlan(Limits{StaticMax: 200000, DynamicMax: 200000, TotalMax: 200000, Source: "changed target limit"})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := p.Add(Request{Name: "stage0", Size: 101377, Alignment: 16, Dynamic: true}); err != nil {
		t.Fatal(err)
	}
	if _, err := StagedQ8CopyFixture(p, tensor); err == nil {
		t.Fatal("forged plan limit bypassed actual target record")
	}
}


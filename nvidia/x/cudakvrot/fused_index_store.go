package cudakvrot

import (
	"fmt"

	"github.com/tmc/lib/nvidia/x/cudaerrors"
	"github.com/tmc/lib/nvidia/x/cudakv"
)

// FusedIndexKVStoreSpec configures paged scatter storage of quantized indexer keys.
type FusedIndexKVStoreSpec struct {
	HeadDim       int
	PageBlockSize int
	UseFP4        bool
}

// Validate checks that s has a valid HeadDim, PageBlockSize, and format configuration.
func (s FusedIndexKVStoreSpec) Validate() error {
	headDim := s.HeadDim
	if headDim == 0 {
		if s.UseFP4 {
			headDim = 64
		} else {
			headDim = 128
		}
	}
	if headDim != 64 && headDim != 128 {
		return fmt.Errorf("cudakvrot: unsupported indexer head dim %d (want 64 or 128): %w", s.HeadDim, cudaerrors.ErrUnsupported)
	}
	blockSize := s.PageBlockSize
	if blockSize == 0 {
		blockSize = 64
	}
	if blockSize <= 0 {
		return fmt.Errorf("cudakvrot: invalid page block size %d: %w", s.PageBlockSize, cudaerrors.ErrUnsupported)
	}
	return nil
}

func (s FusedIndexKVStoreSpec) normalized() (FusedIndexKVStoreSpec, cudakv.KVPageFormatDescriptor, error) {
	if err := s.Validate(); err != nil {
		return FusedIndexKVStoreSpec{}, cudakv.KVPageFormatDescriptor{}, err
	}
	if s.HeadDim == 0 {
		if s.UseFP4 {
			s.HeadDim = 64
		} else {
			s.HeadDim = 128
		}
	}
	if s.PageBlockSize == 0 {
		s.PageBlockSize = 64
	}
	format := cudakv.FormatIndexKV_MXFP8
	if s.UseFP4 {
		format = cudakv.FormatIndexKV_FP4
	}
	desc, err := format.Descriptor()
	if err != nil {
		return FusedIndexKVStoreSpec{}, cudakv.KVPageFormatDescriptor{}, err
	}
	return s, desc, nil
}

// StoreIndexKVPagedCPU scatters quantized indexer keys (68 B for FP4 or 132 B for MXFP8)
// into paged pagePool at (pageTable[seq, pos/PageBlockSize], pos%PageBlockSize) with data
// at [0..DataBytes) and scale at [ScaleOffset..ScaleOffset+ScaleBytes).
func StoreIndexKVPagedCPU(
	kQuant []byte,
	kScale []byte,
	pageTable []int32,
	seqPositions []int32,
	pagePool []byte,
	spec FusedIndexKVStoreSpec,
) error {
	normSpec, desc, err := spec.normalized()
	if err != nil {
		return err
	}
	numTokens := len(seqPositions)
	if numTokens == 0 {
		return nil
	}
	if len(kQuant) != numTokens*desc.DataBytes {
		return fmt.Errorf("cudakvrot: kQuant length %d does not match %d tokens * %d data bytes: %w", len(kQuant), numTokens, desc.DataBytes, cudaerrors.ErrUnsupported)
	}
	if len(kScale) != numTokens*desc.ScaleBytes {
		return fmt.Errorf("cudakvrot: kScale length %d does not match %d tokens * %d scale bytes: %w", len(kScale), numTokens, desc.ScaleBytes, cudaerrors.ErrUnsupported)
	}
	if len(pageTable) == 0 || len(pageTable)%numTokens != 0 {
		return fmt.Errorf("cudakvrot: pageTable length %d must be a positive multiple of numTokens %d: %w", len(pageTable), numTokens, cudaerrors.ErrUnsupported)
	}
	maxBlocksPerSeq := len(pageTable) / numTokens
	pageBytes := int64(normSpec.PageBlockSize) * int64(desc.BytesPerToken)
	if pageBytes <= 0 || int64(len(pagePool)) < pageBytes {
		return fmt.Errorf("cudakvrot: pagePool length %d smaller than single page %d bytes: %w", len(pagePool), pageBytes, cudaerrors.ErrUnsupported)
	}
	totalPages := int64(len(pagePool)) / pageBytes

	for i := 0; i < numTokens; i++ {
		pos := int(seqPositions[i])
		if pos < 0 {
			return fmt.Errorf("cudakvrot: negative sequence position %d at token %d: %w", pos, i, cudaerrors.ErrUnsupported)
		}
		blockIdx := pos / normSpec.PageBlockSize
		tokenInPage := pos % normSpec.PageBlockSize
		if blockIdx >= maxBlocksPerSeq {
			return fmt.Errorf("cudakvrot: block index %d exceeds pageTable stride %d at token %d: %w", blockIdx, maxBlocksPerSeq, i, cudaerrors.ErrUnsupported)
		}
		physPage := int64(pageTable[i*maxBlocksPerSeq+blockIdx])
		if physPage < 0 || physPage >= totalPages {
			return fmt.Errorf("cudakvrot: physical page %d out of range [0, %d) at token %d: %w", physPage, totalPages, i, cudaerrors.ErrUnsupported)
		}
		pageBase := physPage * pageBytes
		nopeOff, _, scaleOff, err := cudakv.TokenSlotOffsets(desc.Format, pageBase, normSpec.PageBlockSize, tokenInPage)
		if err != nil {
			return err
		}
		copy(pagePool[nopeOff:nopeOff+int64(desc.DataBytes)], kQuant[i*desc.DataBytes:(i+1)*desc.DataBytes])
		copy(pagePool[scaleOff:scaleOff+int64(desc.ScaleBytes)], kScale[i*desc.ScaleBytes:(i+1)*desc.ScaleBytes])
	}
	return nil
}

// CompileFusedIndexKVStore generates NVRTC CUDA C++ source for set_index_kv_paged_kernel.
func CompileFusedIndexKVStore(spec FusedIndexKVStoreSpec) (string, error) {
	normSpec, desc, err := spec.normalized()
	if err != nil {
		return "", err
	}
	src := fmt.Sprintf(`// Generated by github.com/tmc/lib/nvidia/x/cudakvrot.CompileFusedIndexKVStore
// Format: %s (BytesPerToken=%d, DataBytes=%d, ScaleOffset=%d, ScaleBytes=%d, PageBlockSize=%d)
extern "C" __global__ void set_index_kv_paged_kernel(
    const unsigned char* __restrict__ k_quant,
    const unsigned char* __restrict__ k_scale,
    const int* __restrict__ page_table,
    const int* __restrict__ seq_positions,
    unsigned char* __restrict__ page_pool,
    int num_tokens,
    int max_blocks_per_seq,
    int total_pages,
    int* __restrict__ status
) {
    int token_idx = blockIdx.x;
    if (token_idx >= num_tokens) return;

    int pos = seq_positions[token_idx];
    if (pos < 0) {
        if (threadIdx.x == 0 && status != nullptr) atomicExch(status, 1);
        return;
    }
    int block_idx = pos / %d;
    int token_in_page = pos %% %d;
    if (block_idx < 0 || block_idx >= max_blocks_per_seq) {
        if (threadIdx.x == 0 && status != nullptr) atomicExch(status, 1);
        return;
    }
    int phys_page = page_table[token_idx * max_blocks_per_seq + block_idx];
    if (phys_page < 0 || phys_page >= total_pages) {
        if (threadIdx.x == 0 && status != nullptr) atomicExch(status, 1);
        return;
    }

    long long slot_base = ((long long)phys_page * %dLL + (long long)token_in_page) * %dLL;
    const unsigned char* src_data = k_quant + (long long)token_idx * %dLL;
    const unsigned char* src_scale = k_scale + (long long)token_idx * %dLL;
    unsigned char* dst_slot = page_pool + slot_base;

    for (int d = threadIdx.x; d < %d; d += blockDim.x) {
        dst_slot[d] = src_data[d];
    }
    for (int s = threadIdx.x; s < %d; s += blockDim.x) {
        dst_slot[%d + s] = src_scale[s];
    }
}
`,
		desc.Format.String(),
		desc.BytesPerToken,
		desc.DataBytes,
		desc.ScaleOffset,
		desc.ScaleBytes,
		normSpec.PageBlockSize,
		normSpec.PageBlockSize,
		normSpec.PageBlockSize,
		normSpec.PageBlockSize,
		desc.BytesPerToken,
		desc.DataBytes,
		desc.ScaleBytes,
		desc.DataBytes,
		desc.ScaleBytes,
		desc.ScaleOffset,
	)
	return src, nil
}

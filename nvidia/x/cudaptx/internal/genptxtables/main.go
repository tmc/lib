// Command genptxtables generates the PTX identifier tables used by cudaptx from
// a local mirror of the PTX ISA documentation.
//
// The docs live in a different module, so they cannot be a build input: this
// command is run by hand and its output is committed.
//
//	go run ./internal/genptxtables -docs $LIBGEN/docs/ptx -out keywords.gen.go
//
// It fails rather than emitting a short table if the documentation's shape
// changes, because markdown structure is not a contract.
package main

import (
	"crypto/sha256"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
)

// wantKeywords is the number of distinct keywords in Table 2 of PTX ISA 9.4.
// The table has 139 cells: selp appears twice.
const (
	wantCells    = 139
	wantKeywords = 138
)

var cell = regexp.MustCompile("`([a-z][a-z0-9_]*)`")

func main() {
	docs := flag.String("docs", "", "path to a docs/ptx mirror")
	out := flag.String("out", "keywords.gen.go", "output file")
	flag.Parse()
	if *docs == "" {
		log.Fatal("genptxtables: -docs is required")
	}

	version, digest, err := source(*docs)
	if err != nil {
		log.Fatalf("genptxtables: %v", err)
	}
	keywords, cells, err := table2(filepath.Join(*docs, "04-syntax.md"))
	if err != nil {
		log.Fatalf("genptxtables: %v", err)
	}
	if cells != wantCells || len(keywords) != wantKeywords {
		log.Fatalf("genptxtables: Table 2 has %d cells and %d distinct keywords, want %d and %d; "+
			"the documentation's shape changed, so review it before updating these constants",
			cells, len(keywords), wantCells, wantKeywords)
	}

	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by internal/genptxtables. DO NOT EDIT.\n//\n")
	fmt.Fprintf(&b, "// Source: PTX ISA %s, Table 2 of docs/ptx/04-syntax.md.\n", version)
	fmt.Fprintf(&b, "// docs/ptx/source.json sha256: %s\n\n", digest)
	fmt.Fprintf(&b, "package cudaptx\n\nimport \"strings\"\n\n")
	fmt.Fprintf(&b, "// PTXISAVersion is the PTX ISA version the generated tables describe.\nconst PTXISAVersion = %q\n\n", version)
	fmt.Fprintf(&b, `// IsInstructionKeyword reports whether mnemonic is one of the %d reserved
// instruction keywords of PTX ISA %s.
//
// A false result does not mean the mnemonic is invalid: ptxas, not this table,
// decides what PTX is accepted, and a newer ISA has keywords this table does
// not. Use it to audit parser output, never to reject input.
func IsInstructionKeyword(mnemonic string) bool {
	_, ok := instructionKeywords[strings.ToLower(mnemonic)]
	return ok
}

`, len(keywords), version)
	fmt.Fprintf(&b, "var instructionKeywords = map[string]struct{}{\n")
	for _, k := range keywords {
		fmt.Fprintf(&b, "\t%q: {},\n", k)
	}
	fmt.Fprintf(&b, "}\n")

	src, err := format.Source([]byte(b.String()))
	if err != nil {
		log.Fatalf("genptxtables: format: %v", err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatalf("genptxtables: %v", err)
	}
	fmt.Printf("%s: %d keywords from PTX ISA %s\n", *out, len(keywords), version)
}

// source reads the mirror's provenance record.
func source(docs string) (version, digest string, err error) {
	path := filepath.Join(docs, "source.json")
	data, err := os.ReadFile(path)
	if err != nil {
		return "", "", err
	}
	var meta struct {
		Version string `json:"version"`
		SHA256  string `json:"sha256"`
	}
	if err := json.Unmarshal(data, &meta); err != nil {
		return "", "", fmt.Errorf("%s: %w", path, err)
	}
	if meta.Version == "" {
		return "", "", fmt.Errorf("%s: no version", path)
	}
	sum := sha256.Sum256(data)
	if meta.SHA256 != "" {
		return meta.Version, meta.SHA256, nil
	}
	return meta.Version, fmt.Sprintf("%x", sum), nil
}

// table2 extracts the reserved instruction keywords from the markdown table
// that follows the "Reserved Instruction Keywords" caption.
func table2(path string) (keywords []string, cells int, err error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, 0, err
	}
	lines := strings.Split(string(data), "\n")
	end := -1
	for i, l := range lines {
		if strings.Contains(l, "Reserved Instruction Keywords") && !strings.HasPrefix(l, "|") {
			end = i
			break
		}
	}
	if end < 0 {
		return nil, 0, fmt.Errorf("%s: no Table 2 caption", path)
	}
	// Walk back over the table rows preceding the caption.
	start := end
	for start > 0 && (strings.HasPrefix(lines[start-1], "|") || strings.TrimSpace(lines[start-1]) == "") {
		start--
	}
	seen := map[string]bool{}
	for _, l := range lines[start:end] {
		if !strings.HasPrefix(l, "|") || strings.Contains(l, "---") {
			continue
		}
		for _, m := range cell.FindAllStringSubmatch(l, -1) {
			cells++
			if !seen[m[1]] {
				seen[m[1]] = true
				keywords = append(keywords, m[1])
			}
		}
	}
	sort.Strings(keywords)
	return keywords, cells, nil
}

package cudaptx_test

import (
	"strings"
	"testing"

	"github.com/tmc/lib/nvidia/x/cudaptx"
)

const samplePTX = `// Generated by NVIDIA NVVM Compiler
.version 8.0
.target sm_90
.address_size 64

.visible .entry EmbeddingLookup(
	.param .u64 p0
)
{
	ld.param.u64 %rd1, [p0];
	ret;
}

.visible .entry RMSNorm(
	.param .u64 p0
)
{
	fma.rn.f32 %f1, %f2, %f3, %f4;
	rsqrt.approx.f32 %f5, %f1;
	st.global.f32 [%rd1], %f5;
	ret;
}

.entry LinearGEMV(
	.param .u64 p0
)
{
	fma.rn.f32 %f10, %f11, %f12, %f13;
	shfl.sync.down.b32 %r1, %r2, 16, 31, 0xffffffff;
	st.global.f32 [%rd2], %f10;
	ret;
}
`

func TestParse(t *testing.T) {
	mod, err := cudaptx.ParseString(samplePTX)
	if err != nil {
		t.Fatalf("ParseString failed: %v", err)
	}

	if mod.Version != "8.0" {
		t.Errorf("expected version 8.0, got %q", mod.Version)
	}
	if mod.Target != "sm_90" {
		t.Errorf("expected target sm_90, got %q", mod.Target)
	}
	if mod.AddressSize != 64 {
		t.Errorf("expected address size 64, got %d", mod.AddressSize)
	}
	if len(mod.Kernels) != 3 {
		t.Fatalf("expected 3 kernels, got %d", len(mod.Kernels))
	}

	embed := mod.Kernel("EmbeddingLookup")
	if embed == nil {
		t.Fatal("expected EmbeddingLookup kernel")
	}
	if embed.StartLine != 6 {
		t.Errorf("expected EmbeddingLookup start line 6, got %d", embed.StartLine)
	}

	norm := mod.Kernel("RMSNorm")
	if norm == nil {
		t.Fatal("expected RMSNorm kernel")
	}
	if fmaLine := mod.FirstOpcodeLine("RMSNorm", "fma"); fmaLine != 18 {
		t.Errorf("expected RMSNorm fma at line 18, got %d", fmaLine)
	}
	if rsqrtLine := mod.FirstOpcodeLine("RMSNorm", "rsqrt"); rsqrtLine != 19 {
		t.Errorf("expected RMSNorm rsqrt at line 19, got %d", rsqrtLine)
	}
	if stLine := mod.FirstOpcodeLine("RMSNorm", "st.global"); stLine != 20 {
		t.Errorf("expected RMSNorm st.global at line 20, got %d", stLine)
	}

	gemv := mod.Kernel("LinearGEMV")
	if gemv == nil {
		t.Fatal("expected LinearGEMV kernel")
	}
	if shflLine := mod.FirstOpcodeLine("LinearGEMV", "shfl"); shflLine != 29 {
		t.Errorf("expected LinearGEMV shfl at line 29, got %d", shflLine)
	}
}

func TestParseReader(t *testing.T) {
	r := strings.NewReader(samplePTX)
	mod, err := cudaptx.Parse(r)
	if err != nil {
		t.Fatalf("Parse failed: %v", err)
	}
	if len(mod.Kernels) != 3 {
		t.Fatalf("expected 3 kernels, got %d", len(mod.Kernels))
	}
}

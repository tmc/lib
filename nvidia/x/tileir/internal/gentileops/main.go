package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
	"strings"
)

func main() {
	log.SetFlags(0)
	log.SetPrefix("gentileops: ")
	root := flag.String("root", "", "path to a github.com/NVIDIA/cuda-tile checkout")
	out := flag.String("out", "", "Go file to write")
	dump := flag.Bool("dump", false, "print the parsed shapes instead of generating")
	flag.Parse()
	if *root == "" {
		log.Fatal("-root is required")
	}
	ops, err := load(*root)
	if err != nil {
		log.Fatal(err)
	}
	if *dump {
		sort.Slice(ops, func(i, j int) bool { return ops[i].Mnemonic < ops[j].Mnemonic })
		for _, op := range ops {
			if !op.HasOpcode {
				continue
			}
			fmt.Printf("%-28s 0x%02X results=%d variadicResults=%v operands=%d count=%v segments=%v attrs=%d flags=%d regions=%d\n",
				op.Mnemonic, op.Opcode, len(op.Results), op.VariadicResults(),
				len(op.Operands()), op.EncodeOperandCount(), op.AttrSizedOperandSegments(),
				len(op.Attributes()), len(op.FlagBits()), op.Regions)
		}
		return
	}
	if *out == "" {
		log.Fatal("-out is required")
	}
	src, err := generate(ops)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// generate renders the operation table as Go source.
func generate(ops []Op) ([]byte, error) {
	withOpcode := ops[:0:0]
	for _, op := range ops {
		if op.HasOpcode && op.Mnemonic != "" {
			withOpcode = append(withOpcode, op)
		}
	}
	sort.Slice(withOpcode, func(i, j int) bool { return withOpcode[i].Mnemonic < withOpcode[j].Mnemonic })

	var buf bytes.Buffer
	fmt.Fprintf(&buf, `// Code generated by gentileops; DO NOT EDIT.

package tileir

// opSpecs describes the bytecode encoding shape of every Tile IR operation
// that has an opcode, derived from NVIDIA's TableGen sources. After the
// opcode, an operation is written as result types, a flags varint,
// attributes, operands and regions; this table says how many of each, which
// carry counts, and which bit of the flags field each optional field owns.
//
// Keys are dialect-qualified mnemonics, as they appear in textual Tile IR.
var opSpecs = map[string]opSpec{
`)
	for _, op := range withOpcode {
		fmt.Fprintf(&buf, "\t%q: {\n", "cuda_tile."+op.Mnemonic)
		fmt.Fprintf(&buf, "\t\tOpcode: 0x%02X,\n", op.Opcode)
		fmt.Fprintf(&buf, "\t\tNumResults: %d, VariadicResults: %v,\n", len(op.Results), op.VariadicResults())
		fmt.Fprintf(&buf, "\t\tOperands: %s, EncodeOperandCount: %v, AttrSegments: %v,\n",
			operandKinds(op), op.EncodeOperandCount(), op.AttrSizedOperandSegments())
		fmt.Fprintf(&buf, "\t\tAttributes: %s,\n", attrSpecs(op))
		fmt.Fprintf(&buf, "\t\tFlags: %s,\n", flagBits(op))
		fmt.Fprintf(&buf, "\t\tNumRegions: %d,\n", op.Regions)
		fmt.Fprintf(&buf, "\t},\n")
	}
	fmt.Fprintf(&buf, "}\n")

	fmt.Fprintf(&buf, `
// OpcodeNames maps Tile IR opcodes to their dialect-qualified mnemonics,
// spelled as NVIDIA's dialect spells them.
var OpcodeNames = map[uint32]string{
`)
	byOpcode := append([]Op(nil), withOpcode...)
	sort.Slice(byOpcode, func(i, j int) bool { return byOpcode[i].Opcode < byOpcode[j].Opcode })
	for _, op := range byOpcode {
		fmt.Fprintf(&buf, "\t0x%02X: %q,\n", op.Opcode, "cuda_tile."+op.Mnemonic)
	}
	fmt.Fprintf(&buf, "}\n")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("formatting generated source: %w", err)
	}
	return src, nil
}

// operandKinds renders an operand kind slice literal.
func operandKinds(op Op) string {
	ops := op.Operands()
	if len(ops) == 0 {
		return "nil"
	}
	parts := make([]string, len(ops))
	for i, a := range ops {
		switch a.Kind {
		case ArgVariadicOperand:
			parts[i] = "operandVariadic"
		case ArgOptionalOperand:
			parts[i] = "operandOptional"
		default:
			parts[i] = "operandPlain"
		}
	}
	return "[]operandKind{" + strings.Join(parts, ", ") + "}"
}

// attrSpecs renders an attribute slice literal. Order is the ODS declaration
// order, which is the order the writer emits payloads in.
func attrSpecs(op Op) string {
	attrs := op.Attributes()
	if len(attrs) == 0 {
		return "nil"
	}
	parts := make([]string, len(attrs))
	for i, a := range attrs {
		parts[i] = fmt.Sprintf("{Name: %q, Optional: %v, Unit: %v}",
			a.Name, a.Optional(), a.Kind == ArgUnitAttribute)
	}
	return "[]attrSpec{" + strings.Join(parts, ", ") + "}"
}

// flagBits renders the flags bit assignment, low bit first.
func flagBits(op Op) string {
	bits := op.FlagBits()
	if len(bits) == 0 {
		return "nil"
	}
	parts := make([]string, len(bits))
	for i, b := range bits {
		parts[i] = fmt.Sprintf("{Name: %q, Operand: %v, Index: %d}", b.Name, b.Operand, b.Index)
	}
	return "[]flagBit{" + strings.Join(parts, ", ") + "}"
}

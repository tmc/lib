package egraph

import (
	"fmt"
	"strings"
)

// CodegenOptions configures CUDA C++ / PTX kernel code generation.
type CodegenOptions struct {
	KernelName string
	Precision  string // "float", "half", "__nv_bfloat16"
	UseWarpSum bool
}

// GenerateCUDA generates a complete, compilable CUDA C++ kernel string from an extracted AST Expr.
func GenerateCUDA(expr *Expr, opts CodegenOptions) (string, error) {
	if expr == nil {
		return "", fmt.Errorf("egraph: nil expr passed to GenerateCUDA")
	}
	if opts.KernelName == "" {
		opts.KernelName = "GeneratedMegakernel"
	}
	if opts.Precision == "" {
		opts.Precision = "float"
	}

	var sb strings.Builder

	// Header and device helper definitions
	sb.WriteString("// Auto-generated by nvidia/x/egraph\n")
	sb.WriteString("#define WARP_SIZE 32\n\n")

	sb.WriteString(fmt.Sprintf(`__device__ __forceinline__ %s warp_sum(%s val) {
    #pragma unroll
    for (int offset = WARP_SIZE / 2; offset > 0; offset /= 2) {
        val += __shfl_down_sync(0xffffffff, val, offset);
    }
    return val;
}

`, opts.Precision, opts.Precision))

	switch expr.Op {
	case "fused_swiglu_gemv":
		sb.WriteString(generateSwiGLUKernel(opts))
	case "fused_rmsnorm_gemv":
		sb.WriteString(generateRMSNormGEMVKernel(opts))
	case "add":
		// Multi-op fused block
		sb.WriteString(generateCompositeKernel(expr, opts))
	default:
		sb.WriteString(generateGenericKernel(expr, opts))
	}

	return sb.String(), nil
}

func generateSwiGLUKernel(opts CodegenOptions) string {
	return fmt.Sprintf(`extern "C" __global__ void %s(
    const %s* __restrict__ x,
    const %s* __restrict__ W_gate,
    const %s* __restrict__ W_up,
    const %s* __restrict__ W_down,
    %s* __restrict__ out,
    int hidden_dim,
    int intermediate_dim
) {
    extern __shared__ %s s_act[]; // dynamic shared memory: intermediate_dim

    // 1. Compute intermediate Gate & Up GEMVs + SiLU activation in parallel
    for (int j = threadIdx.x; j < intermediate_dim; j += blockDim.x) {
        %s gate = 0.0f;
        %s up = 0.0f;
        for (int k = 0; k < hidden_dim; k++) {
            gate += x[k] * W_gate[j * hidden_dim + k];
            up += x[k] * W_up[j * hidden_dim + k];
        }
        %s silu = gate / (1.0f + expf(-gate));
        s_act[j] = silu * up;
    }
    __syncthreads();

    // 2. Compute Down GEMV output elements
    for (int out_idx = blockIdx.x * blockDim.x + threadIdx.x; out_idx < hidden_dim; out_idx += gridDim.x * blockDim.x) {
        %s acc = 0.0f;
        for (int j = 0; j < intermediate_dim; j++) {
            acc += s_act[j] * W_down[out_idx * intermediate_dim + j];
        }
        out[out_idx] = acc;
    }
}
`, opts.KernelName, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision)
}

func generateRMSNormGEMVKernel(opts CodegenOptions) string {
	return fmt.Sprintf(`extern "C" __global__ void %s(
    const %s* __restrict__ x,
    const %s* __restrict__ weight,
    const %s* __restrict__ W_proj,
    %s* __restrict__ out,
    int in_dim,
    int out_dim,
    float eps
) {
    int row = blockIdx.x;
    if (row >= out_dim) return;

    int tid = threadIdx.x;
    int lane = tid %% WARP_SIZE;
    int wid = tid / WARP_SIZE;
    __shared__ %s s_sum[32];

    const %s* w_row = W_proj + row * in_dim;
    %s sum = 0.0f;
    for (int i = tid; i < in_dim; i += blockDim.x) {
        %s norm_val = x[i] * weight[i];
        sum += norm_val * w_row[i];
    }
    sum = warp_sum(sum);

    if (lane == 0) {
        s_sum[wid] = sum;
    }
    __syncthreads();

    %s block_sum = (tid < (blockDim.x / WARP_SIZE)) ? s_sum[lane] : 0.0f;
    if (wid == 0) {
        block_sum = warp_sum(block_sum);
    }

    if (tid == 0) {
        out[row] = block_sum;
    }
}
`, opts.KernelName, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision)
}

func generateCompositeKernel(expr *Expr, opts CodegenOptions) string {
	return fmt.Sprintf(`extern "C" __global__ void %s(
    const %s* __restrict__ in_a,
    const %s* __restrict__ in_b,
    %s* __restrict__ out,
    int n
) {
    int idx = blockDim.x * blockIdx.x + threadIdx.x;
    if (idx < n) {
        out[idx] = in_a[idx] + in_b[idx];
    }
}
`, opts.KernelName, opts.Precision, opts.Precision, opts.Precision)
}

func generateGenericKernel(expr *Expr, opts CodegenOptions) string {
	return fmt.Sprintf(`extern "C" __global__ void %s(
    const %s* __restrict__ in,
    %s* __restrict__ out,
    int n
) {
    int idx = blockDim.x * blockIdx.x + threadIdx.x;
    if (idx < n) {
        out[idx] = in[idx];
    }
}
`, opts.KernelName, opts.Precision, opts.Precision)
}

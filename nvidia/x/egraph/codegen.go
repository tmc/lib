func generateQ2KMatvecKernel(opts CodegenOptions) string {
	src := `// Q2_K matrix-vector multiplication kernel (y = W * x).
// Requirements:
// - cols must be a positive multiple of 256 (the Q2_K super-block size QK_K).
//   If cols is not a multiple of 256, lane 0 writes NaN to y[row] to prevent
//   uninitialized buffer reuse.
// - blockDim.x must be a multiple of 32 (WARP_SIZE), with each warp processing one row.
extern "C" __global__ void KERNEL_NAME(
    const block_q2_k* __restrict__ W,
    ACT_TYPE __restrict__ x,
    float* __restrict__ y,
    int rows,
    int cols
) {
    int warp_id = (blockIdx.x * blockDim.x + threadIdx.x) / WARP_SIZE;
    int lane = threadIdx.x % WARP_SIZE;
    if (warp_id >= rows) return;

    int row = warp_id;
    if (cols <= 0 || cols % 256 != 0) {
        if (lane == 0) {
            y[row] = __int_as_float(0x7fffffff);
        }
        return;
    }
    int blocks_per_row = cols / 256;
    float row_sum = 0.0f;

    for (int b = 0; b < blocks_per_row; b++) {
        const block_q2_k* blk = &W[row * blocks_per_row + b];
        float d = half_to_float(blk->d);
        float dmin = half_to_float(blk->dmin);

        float acc = 0.0f;
        for (int i = 0; i < 8; i++) {
            int elem = lane * 8 + i;
            int group = elem / 16;
            int l = elem - group * 16;
            int base = 32 * (group / 8) + 16 * (group & 1);
            int shift = ((group / 2) & 3) * 2;
            uint8_t q_val = (blk->qs[base + l] >> shift) & 0x03;
            uint8_t sc = blk->scales[group];
            float val = d * (float)(sc & 0x0f) * (float)q_val - dmin * (float)(sc >> 4);
            acc += val * ACT_LOAD(x, b * 256 + elem);
        }

        for (int offset = 16; offset > 0; offset /= 2) {
            acc += __shfl_down_sync(FULL_WARP_MASK, acc, offset);
        }
        if (lane == 0) {
            row_sum += acc;
        }
    }
    if (lane == 0) {
        y[row] = row_sum;
    }
}
`
	src = strings.ReplaceAll(src, "ACT_TYPE", activationType(opts.Precision))
	src = strings.ReplaceAll(src, "ACT_LOAD", activationLoad(opts.Precision))
	return strings.ReplaceAll(src, "KERNEL_NAME", opts.KernelName)
}

func generateIQ2XXSMatvecKernel(opts CodegenOptions) string {
	src := `// IQ2_XXS matrix-vector multiplication kernel (y = W * x).
// Requirements:
// - cols must be a positive multiple of 256 (the IQ2_XXS block size).
//   If cols is not a multiple of 256, lane 0 writes NaN to y[row] to prevent
//   uninitialized buffer reuse.
// - blockDim.x must be a multiple of 32 (WARP_SIZE), with each warp processing one row.
extern "C" __global__ void KERNEL_NAME(
    const block_iq2_xxs* __restrict__ W,
    ACT_TYPE __restrict__ x,
    float* __restrict__ y,
    int rows,
    int cols
) {
    int warp_id = (blockIdx.x * blockDim.x + threadIdx.x) / WARP_SIZE;
    int lane = threadIdx.x % WARP_SIZE;
    if (warp_id >= rows) return;

    int row = warp_id;
    if (cols <= 0 || cols % 256 != 0) {
        if (lane == 0) {
            y[row] = __int_as_float(0x7fffffff);
        }
        return;
    }
    int blocks_per_row = cols / 256;
    float row_sum = 0.0f;

    int ib32 = lane >> 2;
    int l = lane & 3;

    for (int b = 0; b < blocks_per_row; b++) {
        const block_iq2_xxs* blk = &W[row * blocks_per_row + b];
        float d = half_to_float(blk->d);

        // block_iq2_xxs is 66 bytes, so blk->qs is 4-byte aligned only for even
        // blocks. Assemble the two 32-bit auxiliaries from uint16_t loads
        // rather than casting, which faults with MISALIGNED_ADDRESS.
        const uint16_t* qs16 = blk->qs + 4 * ib32;
        uint32_t aux0 = (uint32_t)qs16[0] | ((uint32_t)qs16[1] << 16);
        uint32_t aux1 = (uint32_t)qs16[2] | ((uint32_t)qs16[3] << 16);

        float db = d * (0.5f + (float)(aux1 >> 28)) * 0.25f;
        uint8_t grid_idx = (aux0 >> (8 * l)) & 0xff;
        uint8_t sign_idx = (aux1 >> (7 * l)) & 0x7f;
        uint8_t signs = ksigns_iq2xs[sign_idx];
        unsigned long long grid_entry = iq2xxs_grid[grid_idx];

        float acc = 0.0f;
        #pragma unroll
        for (int i = 0; i < 8; i++) {
            float grid_val = (float)((uint8_t)(grid_entry >> (8 * i)));
            float sign = (signs & kmask_iq2xs[i]) ? -1.0f : 1.0f;
            float w = db * grid_val * sign;
            acc += w * ACT_LOAD(x, b * 256 + lane * 8 + i);
        }

        for (int offset = 16; offset > 0; offset /= 2) {
            acc += __shfl_down_sync(FULL_WARP_MASK, acc, offset);
        }
        if (lane == 0) {
            row_sum += acc;
        }
    }
    if (lane == 0) {
        y[row] = row_sum;
    }
}
`
	src = strings.ReplaceAll(src, "ACT_TYPE", activationType(opts.Precision))
	src = strings.ReplaceAll(src, "ACT_LOAD", activationLoad(opts.Precision))
	return strings.ReplaceAll(src, "KERNEL_NAME", opts.KernelName)
}

func generateFusedRoPEStoreKVKernel(opts CodegenOptions) string {
	src := `extern "C" __global__ void KERNEL_NAME(
    const float* __restrict__ q,
    const float* __restrict__ k,
    const float* __restrict__ v,
    float* __restrict__ out_q,
    float* __restrict__ k_cache,
    float* __restrict__ v_cache,
    int pos,
    float theta,
    int q_dim,
    int kv_dim,
    int head_dim,
    int max_seq_len
) {
    int idx = blockIdx.x * blockDim.x + threadIdx.x;
    if (idx < q_dim) {
        int head_idx = idx % head_dim;
        int pair_idx = head_idx / 2;
        float freq = 1.0f / powf(theta, (float)(pair_idx * 2) / (float)head_dim);
        float angle = (float)pos * freq;
        float cos_val = cosf(angle);
        float sin_val = sinf(angle);

        float q_val = q[idx];
        if (head_idx % 2 == 0) {
            float q_pair = (idx + 1 < q_dim) ? q[idx + 1] : 0.0f;
            out_q[idx] = q_val * cos_val - q_pair * sin_val;
        } else {
            float q_pair = (idx > 0) ? q[idx - 1] : 0.0f;
            out_q[idx] = q_pair * sin_val + q_val * cos_val;
        }
    }
    if (idx < kv_dim) {
        int head_idx = idx % head_dim;
        int pair_idx = head_idx / 2;
        float freq = 1.0f / powf(theta, (float)(pair_idx * 2) / (float)head_dim);
        float angle = (float)pos * freq;
        float cos_val = cosf(angle);
        float sin_val = sinf(angle);

        float k_val = k[idx];
        float rotated_k;
        if (head_idx % 2 == 0) {
            float k_pair = (idx + 1 < kv_dim) ? k[idx + 1] : 0.0f;
            rotated_k = k_val * cos_val - k_pair * sin_val;
        } else {
            float k_pair = (idx > 0) ? k[idx - 1] : 0.0f;
            rotated_k = k_pair * sin_val + k_val * cos_val;
        }
        int cache_idx = pos * kv_dim + idx;
        k_cache[cache_idx] = rotated_k;
        v_cache[cache_idx] = v[idx];
    }
}
`
	return strings.ReplaceAll(src, "KERNEL_NAME", opts.KernelName)
}


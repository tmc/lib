package egraph

import (
	"fmt"
	"strings"
)

// CodegenOptions configures CUDA C++ / PTX kernel code generation.
type CodegenOptions struct {
	KernelName string
	// Precision is the element type the kernel operates on.
	// Supported precisions:
	//   - "float", "float32" (default: IEEE 754 single-precision)
	//   - "half", "float16" (16-bit half precision via native PTX conversions without external headers)
	//   - "q8_0" (8-bit quantization with half-precision scale)
	//   - "u2" (2-bit packed unsigned quantization with dp4a SIMD unpacking)
	//   - "q2_k" (2-bit k-quantization with super-block scaling and interleaved quants)
	Precision string
	// UseWarpSum enables intra-warp reduction helpers.
	UseWarpSum bool
}

// GenerateCUDA generates a complete, compilable CUDA C++ kernel from an
// extracted AST Expr.
//
// It supports floating-point and DeepSeek-V4 (ds4-min) quantized operators:
//   - "fused_swiglu_gemv" (float / half FFN fusion)
//   - "fused_swiglu_q8_0" (Q8_0 quantized FFN fusion)
//   - "fused_rmsnorm_gemv" (RMSNorm reduction + GEMV projection)
//   - "q8_0_matvec" (Q8_0 quantized matrix-vector multiply with warp reduction)
//   - "u2_simd" (2-bit packed unsigned dot product via dp4a SIMD)
//   - "u2_scalar" (2-bit packed unsigned dot product via scalar shifts)
//   - "q2_k_matvec" (Q2_K quantized matrix-vector multiply with interleaved quants)
//   - "fused_rope_store_kv" (RoPE rotation + KV-cache store)
//   - "add" (two-input elementwise addition)
func GenerateCUDA(expr *Expr, opts CodegenOptions) (string, error) {
	if expr == nil {
		return "", fmt.Errorf("egraph: nil expr passed to GenerateCUDA")
	}
	if opts.KernelName == "" {
		opts.KernelName = "GeneratedMegakernel"
	}
	if opts.Precision == "" {
		opts.Precision = "float"
	}

	switch opts.Precision {
	case "float", "float32", "half", "float16", "q8_0", "u2", "q2_k":
		// supported precisions
	default:
		return "", fmt.Errorf("egraph: unsupported precision %q: supported precisions are \"float\", \"half\", \"q8_0\", \"u2\", \"q2_k\"", opts.Precision)
	}

	var sb strings.Builder

	// Header and device helper definitions
	sb.WriteString("// Auto-generated by nvidia/x/egraph\n")
	sb.WriteString(`#ifndef EGRAPH_COMMON_DEFINED
#define EGRAPH_COMMON_DEFINED

#define WARP_SIZE 32
#define FULL_WARP_MASK 0xffffffff

#if defined(__CUDACC_RTC__)
typedef signed char int8_t;
typedef unsigned char uint8_t;
typedef unsigned short uint16_t;
typedef unsigned int uint32_t;
typedef long long int64_t;
#else
#include <stdint.h>
#endif

// Half-to-float conversion using native PTX instruction without external headers.
__device__ __forceinline__ float half_to_float(uint16_t h) {
    float f;
    asm("cvt.f32.f16 %0, %1;" : "=f"(f) : "h"(h));
    return f;
}

// Float-to-half conversion using native PTX instruction without external headers.
__device__ __forceinline__ uint16_t float_to_half(float f) {
    uint16_t h;
    asm("cvt.rn.f16.f32 %0, %1;" : "=h"(h) : "f"(f));
    return h;
}

// 4-way 8-bit SIMD dot product using native PTX instruction.
__device__ __forceinline__ int dp4a_simd(int a, int b, int c) {
#if defined(__CUDA_ARCH__) && __CUDA_ARCH__ >= 610
    int d;
    asm("dp4a.s32.s32 %0, %1, %2, %3;" : "=r"(d) : "r"(a), "r"(b), "r"(c));
    return d;
#else
    return __dp4a(a, b, c);
#endif
}

// Q8_0 block: 32 signed 8-bit quantized values with a 16-bit half scale.
struct block_q8_0 {
    uint16_t d;        // float16 scale
    int8_t qs[32];     // 32 int8 quantized values
};

// Q2_K block: 256 2-bit quantized values with super-block scaling.
// Laid out as block_q2_K (ds4.c:846, lm/quant/kquant.go:34).
struct block_q2_k {
    uint8_t scales[16]; // low nibble scales quant, high nibble scales min
    uint8_t qs[64];     // 256 2-bit weights, interleaved
    uint16_t d;         // float16 super-block scale for quants
    uint16_t dmin;      // float16 super-block scale for minimums
};

__device__ __forceinline__ float warp_sum(float val) {
    #pragma unroll
    for (int offset = WARP_SIZE / 2; offset > 0; offset /= 2) {
        val += __shfl_down_sync(FULL_WARP_MASK, val, offset);
    }
    return val;
}

#endif // EGRAPH_COMMON_DEFINED

`)

	switch expr.Op {
	case "fused_swiglu_gemv":
		sb.WriteString(generateSwiGLUKernel(opts))
	case "fused_swiglu_q8_0":
		sb.WriteString(generateSwiGLUQ8_0Kernel(opts))
	case "fused_rmsnorm_gemv":
		sb.WriteString(generateRMSNormGEMVKernel(opts))
	case "q8_0_matvec":
		sb.WriteString(generateQ8_0MatvecKernel(opts))
	case "u2_simd":
		sb.WriteString(generateU2SIMDKernel(opts))
	case "u2_scalar":
		sb.WriteString(generateU2ScalarKernel(opts))
	case "q2_k_matvec":
		sb.WriteString(generateQ2KMatvecKernel(opts))
	case "fused_rope_store_kv":
		sb.WriteString(generateFusedRoPEStoreKVKernel(opts))
	case "add":
		if len(expr.Children) != 2 || len(expr.Children[0].Children) != 0 || len(expr.Children[1].Children) != 0 {
			return "", fmt.Errorf("egraph: no CUDA kernel for %q: the add kernel is elementwise over two leaf inputs", expr.String())
		}
		sb.WriteString(generateCompositeKernel(expr, opts))
	default:
		return "", fmt.Errorf("egraph: no CUDA kernel for operator %q", expr.Op)
	}

	return sb.String(), nil
}

func generateSwiGLUKernel(opts CodegenOptions) string {
	scalarType := "float"
	if opts.Precision == "half" || opts.Precision == "float16" {
		scalarType = "uint16_t"
	}
	return fmt.Sprintf(`extern "C" __global__ void %s(
    const %s* __restrict__ x,
    const %s* __restrict__ W_gate,
    const %s* __restrict__ W_up,
    const %s* __restrict__ W_down,
    %s* __restrict__ out,
    int hidden_dim,
    int intermediate_dim
) {
    extern __shared__ float s_act[]; // dynamic shared memory: intermediate_dim * sizeof(float)

    // 1. Compute intermediate Gate & Up GEMVs + SiLU activation in parallel
    for (int j = threadIdx.x; j < intermediate_dim; j += blockDim.x) {
        float gate = 0.0f;
        float up = 0.0f;
        for (int k = 0; k < hidden_dim; k++) {
            float xv = (float)x[k];
            gate += xv * (float)W_gate[j * hidden_dim + k];
            up += xv * (float)W_up[j * hidden_dim + k];
        }
        float silu = gate / (1.0f + expf(-gate));
        s_act[j] = silu * up;
    }
    __syncthreads();

    // 2. Compute Down GEMV output elements
    for (int out_idx = blockIdx.x * blockDim.x + threadIdx.x; out_idx < hidden_dim; out_idx += gridDim.x * blockDim.x) {
        float acc = 0.0f;
        for (int j = 0; j < intermediate_dim; j++) {
            acc += s_act[j] * (float)W_down[out_idx * intermediate_dim + j];
        }
        out[out_idx] = (%s)acc;
    }
}
`, opts.KernelName, scalarType, scalarType, scalarType, scalarType, scalarType, scalarType)
}

func generateSwiGLUQ8_0Kernel(opts CodegenOptions) string {
	return fmt.Sprintf(`extern "C" __global__ void %s(
    const float* __restrict__ x,
    const block_q8_0* __restrict__ W_gate,
    const block_q8_0* __restrict__ W_up,
    const block_q8_0* __restrict__ W_down,
    float* __restrict__ out,
    int hidden_dim,
    int intermediate_dim
) {
    extern __shared__ float s_act[];
    int blocks_per_hidden = hidden_dim / 32;
    int blocks_per_inter = intermediate_dim / 32;

    for (int j = blockIdx.x * blockDim.x + threadIdx.x; j < intermediate_dim; j += gridDim.x * blockDim.x) {
        float gate = 0.0f;
        float up = 0.0f;
        for (int b = 0; b < blocks_per_hidden; b++) {
            const block_q8_0* blk_g = &W_gate[j * blocks_per_hidden + b];
            const block_q8_0* blk_u = &W_up[j * blocks_per_hidden + b];
            float scale_g = half_to_float(blk_g->d);
            float scale_u = half_to_float(blk_u->d);
            for (int lane = 0; lane < 32; lane++) {
                float xv = x[b * 32 + lane];
                gate += (float)blk_g->qs[lane] * xv * scale_g;
                up += (float)blk_u->qs[lane] * xv * scale_u;
            }
        }
        float silu = gate / (1.0f + expf(-gate));
        s_act[j] = silu * up;
    }
    __syncthreads();

    for (int out_idx = blockIdx.x * blockDim.x + threadIdx.x; out_idx < hidden_dim; out_idx += gridDim.x * blockDim.x) {
        float acc = 0.0f;
        for (int b = 0; b < blocks_per_inter; b++) {
            const block_q8_0* blk_d = &W_down[out_idx * blocks_per_inter + b];
            float scale_d = half_to_float(blk_d->d);
            for (int lane = 0; lane < 32; lane++) {
                acc += (float)blk_d->qs[lane] * s_act[b * 32 + lane] * scale_d;
            }
        }
        out[out_idx] = acc;
    }
}
`, opts.KernelName)
}

func generateRMSNormGEMVKernel(opts CodegenOptions) string {
	scalarType := "float"
	if opts.Precision == "half" || opts.Precision == "float16" {
		scalarType = "uint16_t"
	}
	src := `extern "C" __global__ void KERNEL_NAME(
    const T* __restrict__ x,
    const T* __restrict__ weight,
    const T* __restrict__ W_proj,
    T* __restrict__ out,
    int in_dim,
    int out_dim,
    float eps
) {
    int row = blockIdx.x;
    if (row >= out_dim) return;

    int tid = threadIdx.x;
    int lane = tid % WARP_SIZE;
    int wid = tid / WARP_SIZE;
    int n_warps = (blockDim.x + WARP_SIZE - 1) / WARP_SIZE;
    __shared__ float s_sum[32];
    __shared__ float s_scale;

    // Pass one: the RMS scale, reduced over the whole of x.
    float sq = 0.0f;
    for (int i = tid; i < in_dim; i += blockDim.x) {
        float v = (float)x[i];
        sq += v * v;
    }
    sq = warp_sum(sq);
    if (lane == 0) {
        s_sum[wid] = sq;
    }
    __syncthreads();
    if (wid == 0) {
        float total = (lane < n_warps) ? s_sum[lane] : 0.0f;
        total = warp_sum(total);
        if (lane == 0) {
            s_scale = rsqrtf(total / (float)in_dim + eps);
        }
    }
    __syncthreads();
    float scale = s_scale;
    __syncthreads();

    // Pass two: the projection of the normalised, weighted input.
    const T* w_row = W_proj + row * in_dim;
    float sum = 0.0f;
    for (int i = tid; i < in_dim; i += blockDim.x) {
        sum += ((float)x[i] * scale * (float)weight[i]) * (float)w_row[i];
    }
    sum = warp_sum(sum);
    if (lane == 0) {
        s_sum[wid] = sum;
    }
    __syncthreads();
    if (wid == 0) {
        float total = (lane < n_warps) ? s_sum[lane] : 0.0f;
        total = warp_sum(total);
        if (lane == 0) {
            out[row] = (T)total;
        }
    }
}
`
	src = strings.ReplaceAll(src, "T", scalarType)
	return strings.ReplaceAll(src, "KERNEL_NAME", opts.KernelName)
}

func generateQ8_0MatvecKernel(opts CodegenOptions) string {
	src := `extern "C" __global__ void KERNEL_NAME(
    const block_q8_0* __restrict__ W,
    const float* __restrict__ x,
    float* __restrict__ y,
    int rows,
    int cols
) {
    int warp_id = (blockIdx.x * blockDim.x + threadIdx.x) / WARP_SIZE;
    int lane = threadIdx.x % WARP_SIZE;
    if (warp_id >= rows) return;

    int row = warp_id;
    int blocks_per_row = cols / 32;
    float row_sum = 0.0f;

    for (int b = 0; b < blocks_per_row; b++) {
        const block_q8_0* blk = &W[row * blocks_per_row + b];
        float scale = half_to_float(blk->d);
        float q = (float)blk->qs[lane];
        float xv = x[b * 32 + lane];
        float prod = q * xv;

        for (int offset = 16; offset > 0; offset /= 2) {
            prod += __shfl_down_sync(FULL_WARP_MASK, prod, offset);
        }
        if (lane == 0) {
            row_sum += prod * scale;
        }
    }
    if (lane == 0) {
        y[row] = row_sum;
    }
}
`
	return strings.ReplaceAll(src, "KERNEL_NAME", opts.KernelName)
}

func generateU2SIMDKernel(opts CodegenOptions) string {
	src := `extern "C" __global__ void KERNEL_NAME(
    const uint32_t* __restrict__ q,
    const int8_t* __restrict__ a,
    float* __restrict__ out,
    float scale,
    int n
) {
    int idx = blockIdx.x * blockDim.x + threadIdx.x;
    if (idx >= n) return;

    uint32_t qval = q[idx];
    const uint32_t* a_u32 = reinterpret_cast<const uint32_t*>(a);
    int sum = 0;

    #pragma unroll
    for (int g = 0; g < 4; g++) {
        uint32_t byte_g = (qval >> (8 * g)) & 0xFF;
        uint32_t rep = byte_g * 0x01010101;
        uint32_t mask_shifts = ((rep >> 0) & 0x03) |
                              (((rep >> 2) & 0x03) << 8) |
                              (((rep >> 4) & 0x03) << 16) |
                              (((rep >> 6) & 0x03) << 24);
        sum = dp4a_simd(mask_shifts, a_u32[idx * 4 + g], sum);
    }
    out[idx] = (float)sum * scale;
}
`
	return strings.ReplaceAll(src, "KERNEL_NAME", opts.KernelName)
}

func generateU2ScalarKernel(opts CodegenOptions) string {
	src := `extern "C" __global__ void KERNEL_NAME(
    const uint32_t* __restrict__ q,
    const int8_t* __restrict__ a,
    float* __restrict__ out,
    float scale,
    int n
) {
    int idx = blockIdx.x * blockDim.x + threadIdx.x;
    if (idx >= n) return;

    uint32_t qval = q[idx];
    float sum = 0.0f;

    #pragma unroll
    for (int b = 0; b < 16; b++) {
        int weight = (int)((qval >> (b * 2)) & 0x03);
        float act = (float)a[idx * 16 + b];
        sum += (float)weight * act;
    }
    out[idx] = sum * scale;
}
`
	return strings.ReplaceAll(src, "KERNEL_NAME", opts.KernelName)
}

func generateQ2KMatvecKernel(opts CodegenOptions) string {
	src := `extern "C" __global__ void KERNEL_NAME(
    const block_q2_k* __restrict__ W,
    const float* __restrict__ x,
    float* __restrict__ y,
    int rows,
    int cols
) {
    int warp_id = (blockIdx.x * blockDim.x + threadIdx.x) / WARP_SIZE;
    int lane = threadIdx.x % WARP_SIZE;
    if (warp_id >= rows) return;

    int row = warp_id;
    int blocks_per_row = cols / 256;
    float row_sum = 0.0f;

    for (int b = 0; b < blocks_per_row; b++) {
        const block_q2_k* blk = &W[row * blocks_per_row + b];
        float d = half_to_float(blk->d);
        float dmin = half_to_float(blk->dmin);

        float acc = 0.0f;
        for (int i = 0; i < 8; i++) {
            int elem = lane * 8 + i;
            int group = elem / 16;
            int l = elem - group * 16;
            int base = 32 * (group / 8) + 16 * (group & 1);
            int shift = ((group / 2) & 3) * 2;
            uint8_t q_val = (blk->qs[base + l] >> shift) & 0x03;
            uint8_t sc = blk->scales[group];
            float val = d * (float)(sc & 0x0f) * (float)q_val - dmin * (float)(sc >> 4);
            acc += val * x[b * 256 + elem];
        }

        for (int offset = 16; offset > 0; offset /= 2) {
            acc += __shfl_down_sync(FULL_WARP_MASK, acc, offset);
        }
        if (lane == 0) {
            row_sum += acc;
        }
    }
    if (lane == 0) {
        y[row] = row_sum;
    }
}
`
	return strings.ReplaceAll(src, "KERNEL_NAME", opts.KernelName)
}

func generateFusedRoPEStoreKVKernel(opts CodegenOptions) string {
	src := `extern "C" __global__ void KERNEL_NAME(
    const float* __restrict__ q,
    const float* __restrict__ k,
    const float* __restrict__ v,
    float* __restrict__ out_q,
    float* __restrict__ k_cache,
    float* __restrict__ v_cache,
    int pos,
    float theta,
    int q_dim,
    int kv_dim,
    int head_dim,
    int max_seq_len
) {
    int idx = blockIdx.x * blockDim.x + threadIdx.x;
    if (idx < q_dim) {
        int head_idx = idx % head_dim;
        int pair_idx = head_idx / 2;
        float freq = 1.0f / powf(theta, (float)(pair_idx * 2) / (float)head_dim);
        float angle = (float)pos * freq;
        float cos_val = cosf(angle);
        float sin_val = sinf(angle);

        float q_val = q[idx];
        if (head_idx % 2 == 0) {
            float q_pair = (idx + 1 < q_dim) ? q[idx + 1] : 0.0f;
            out_q[idx] = q_val * cos_val - q_pair * sin_val;
        } else {
            float q_pair = (idx > 0) ? q[idx - 1] : 0.0f;
            out_q[idx] = q_pair * sin_val + q_val * cos_val;
        }
    }
    if (idx < kv_dim) {
        int head_idx = idx % head_dim;
        int pair_idx = head_idx / 2;
        float freq = 1.0f / powf(theta, (float)(pair_idx * 2) / (float)head_dim);
        float angle = (float)pos * freq;
        float cos_val = cosf(angle);
        float sin_val = sinf(angle);

        float k_val = k[idx];
        float rotated_k;
        if (head_idx % 2 == 0) {
            float k_pair = (idx + 1 < kv_dim) ? k[idx + 1] : 0.0f;
            rotated_k = k_val * cos_val - k_pair * sin_val;
        } else {
            float k_pair = (idx > 0) ? k[idx - 1] : 0.0f;
            rotated_k = k_pair * sin_val + k_val * cos_val;
        }
        int cache_idx = pos * kv_dim + idx;
        k_cache[cache_idx] = rotated_k;
        v_cache[cache_idx] = v[idx];
    }
}
`
	return strings.ReplaceAll(src, "KERNEL_NAME", opts.KernelName)
}

func generateCompositeKernel(expr *Expr, opts CodegenOptions) string {
	scalarType := "float"
	if opts.Precision == "half" || opts.Precision == "float16" {
		scalarType = "uint16_t"
	}
	return fmt.Sprintf(`extern "C" __global__ void %s(
    const %s* __restrict__ in_a,
    const %s* __restrict__ in_b,
    %s* __restrict__ out,
    int n
) {
    int idx = blockDim.x * blockIdx.x + threadIdx.x;
    if (idx < n) {
        out[idx] = in_a[idx] + in_b[idx];
    }
}
`, opts.KernelName, scalarType, scalarType, scalarType)
}

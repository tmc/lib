package warpsynth

import (
	"fmt"
	"strings"
)

// ptxVersion returns the PTX ISA version the skeleton declares for arch.
func ptxVersion(arch string) string {
	switch arch {
	case "sm_90a":
		return "8.0"
	case "sm_107a", "sm_107f":
		return "9.4"
	}
	return "8.8"
}

func validName(s string) bool {
	if s == "" {
		return false
	}
	for i, c := range s {
		if c == '_' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z' || i > 0 && c >= '0' && c <= '9' {
			continue
		}
		return false
	}
	return true
}

// EmitWarpSpecializedSkeletonPTX returns a PTX entry kernelName(num_tiles)
// that runs the schedule's ring protocol with the work left as comments:
// role dispatch on %tid.x/32, setmaxnreg per role, mbarrier initialization,
// and per-tile wait loops on (k/D)&1 parity. Each role's warps meet at a
// role-local named barrier (bar.sync 1+role) before one elected thread
// arrives. The producer arrives with expect_tx of 0 bytes, standing in for
// the TMA transaction count. With UseEarlySMEMRelease on a target with
// TMEM, the MMA issuer releases a stage with tcgen05.commit, which arrives
// once the tcgen05 operations before it complete.
//
// The output has not been assembled by this package; see the package
// documentation.
func (s Schedule) EmitWarpSpecializedSkeletonPTX(kernelName string) (string, error) {
	return s.emitPTX(kernelName, protocol{})
}

func (s Schedule) emitPTX(name string, p protocol) (string, error) {
	if err := s.Check(); err != nil {
		return "", fmt.Errorf("emit PTX: %w", err)
	}
	if !validName(name) {
		return "", fmt.Errorf("emit PTX: invalid kernel name %q", name)
	}
	rs := rings(s)
	b := new(strings.Builder)
	w := func(format string, args ...any) { fmt.Fprintf(b, format+"\n", args...) }
	w("// Warp-specialized skeleton generated by package warpsynth.")
	w("// Roles:")
	for _, r := range s.Roles {
		w("//   %-13s warps [%d,%d) setmaxnreg %d", r.Kind, r.FirstWarp, r.FirstWarp+r.Warps, r.Regs)
	}
	for _, t := range s.TMEM {
		w("// TMEM %s: %d columns at %d and %d (of %d allocated)", t.Name, t.Width, t.Cols[0], t.Cols[1], s.TotalTMEMCols)
	}
	w(".version %s", ptxVersion(s.Arch))
	w(".target %s", s.Arch)
	w(".address_size 64")
	w("")
	w(".visible .entry %s(.param .u32 num_tiles)", name)
	w(".reqntid %d, 1, 1", 32*s.TotalWarps)
	w(".maxnreg %d", s.LaunchRegs)
	w("{")
	w("\t.reg .pred %%p<4>;")
	w("\t.reg .b32 %%r<8>;")
	w("\t.reg .b64 %%rd<1>;")
	for i, d := range s.RingDepths {
		w("\t.shared .align 8 .b64 ws_full%d[%d];", i, d)
		w("\t.shared .align 8 .b64 ws_empty%d[%d];", i, d)
	}
	w("")
	w("\tld.param.u32 %%r0, [num_tiles];")
	w("\tmov.u32 %%r1, %%tid.x;")
	w("\tshr.u32 %%r2, %%r1, 5; // warp index; %%warpid is not stable (PTX ISA)")
	w("\tsetp.ne.u32 %%p0, %%r1, 0;")
	w("\t@%%p0 bra $L_init_done;")
	for i, d := range s.RingDepths {
		for st := range d {
			w("\tmbarrier.init.shared::cta.b64 [ws_full%d+%d], 1;", i, 8*st)
			w("\tmbarrier.init.shared::cta.b64 [ws_empty%d+%d], 1;", i, 8*st)
		}
	}
	w("$L_init_done:")
	w("\tbar.sync 0;")
	for i, r := range s.Roles {
		w("\tsetp.lt.u32 %%p0, %%r2, %d;", r.FirstWarp+r.Warps)
		w("\t@%%p0 bra $L_role%d;", i)
	}
	w("\tbra.uni $L_exit;")

	wait := func(label, bar string, ringIdx, depth int, empty bool) {
		w("\trem.u32 %%r4, %%r3, %d;", depth)
		if p.parityByIter {
			w("\tand.b32 %%r5, %%r3, 1;")
		} else {
			w("\tdiv.u32 %%r5, %%r3, %d;", depth)
			w("\tand.b32 %%r5, %%r5, 1;")
		}
		if empty {
			w("\txor.b32 %%r5, %%r5, 1;")
		}
		w("\tmov.u32 %%r6, %s%d;", bar, ringIdx)
		w("\tmad.lo.u32 %%r6, %%r4, 8, %%r6;")
		w("%s:", label)
		w("\tmbarrier.try_wait.parity.shared::cta.b64 %%p1, [%%r6], %%r5;")
		w("\t@!%%p1 bra %s;", label)
	}
	arrive := func(bar string, ringIdx, depth int, how string) {
		w("\trem.u32 %%r4, %%r3, %d;", depth)
		w("\tmov.u32 %%r6, %s%d;", bar, ringIdx)
		w("\tmad.lo.u32 %%r6, %%r4, 8, %%r6;")
		switch how {
		case "tx":
			w("\t@%%p3 mbarrier.arrive.expect_tx.shared::cta.b64 %%rd0, [%%r6], 0; // TMA transaction bytes go here")
		case "commit":
			w("\t@%%p3 tcgen05.commit.cta_group::1.mbarrier::arrive::one.shared::cluster.b64 [%%r6];")
		default:
			w("\t@%%p3 mbarrier.arrive.shared::cta.b64 %%rd0, [%%r6];")
		}
	}

	for i, r := range s.Roles {
		w("")
		w("$L_role%d: // %s", i, r.Kind)
		switch {
		case r.Regs < s.LaunchRegs:
			w("\tsetmaxnreg.dec.sync.aligned.u32 %d;", r.Regs)
		case r.Regs > s.LaunchRegs:
			w("\tsetmaxnreg.inc.sync.aligned.u32 %d;", r.Regs)
		}
		w("\tsetp.eq.u32 %%p3, %%r1, %d; // elected thread", 32*r.FirstWarp)
		w("\tmov.u32 %%r3, 0;")
		w("$L_role%d_loop:", i)
		w("\tsetp.ge.u32 %%p0, %%r3, %%r0;")
		w("\t@%%p0 bra $L_exit;")
		if i > 0 {
			wait(fmt.Sprintf("$L_role%d_full", i), "ws_full", i-1, rs[i-1].depth, false)
		}
		if i < len(rs) && !(i == 0 && p.skipEmptyWait) {
			wait(fmt.Sprintf("$L_role%d_empty", i), "ws_empty", i, rs[i].depth, true)
		}
		switch r.Kind {
		case RoleTMAProducer:
			w("\t// cp.async.bulk.tensor into stage k%%%d, completing on ws_full0", rs[0].depth)
		case RoleMMAIssuer:
			w("\t// tcgen05.mma reading stage k%%%d into the TMEM accumulator", rs[0].depth)
		case RoleEpilogueMath:
			w("\t// tcgen05.ld of the accumulator, epilogue math")
		case RoleFabricStorer:
			w("\t// TMA store or fabric put of the staged tile")
		}
		w("\tbar.sync %d, %d;", 1+i, 32*r.Warps)
		if i < len(rs) {
			how := ""
			if i == 0 {
				how = "tx"
			}
			arrive("ws_full", i, rs[i].depth, how)
		}
		for j, rg := range rs {
			if rg.releaser != i {
				continue
			}
			how := ""
			if j == 0 && i == 1 && s.UseEarlySMEMRelease && TMEMColumns(s.Arch) > 0 {
				how = "commit"
			}
			arrive("ws_empty", j, rg.depth, how)
		}
		w("\tadd.u32 %%r3, %%r3, 1;")
		w("\tbra.uni $L_role%d_loop;", i)
	}
	w("")
	w("$L_exit:")
	w("\tret;")
	w("}")
	return b.String(), nil
}

// HostEmuElems is the number of floats per tile in [Schedule.EmitHostEmuCUDA].
const HostEmuElems = 32

// EmitHostEmuCUDA returns CUDA C++ for package cudahostemu that runs the
// schedule's ring protocol over numTiles tiles. kernelName(in, out) copies
// each tile of HostEmuElems floats from in into a ring stage with
// cp.async.bulk, and the following roles compute out = 2·in + 1 through the
// remaining rings, with the same waits, parities, role-local barriers,
// elected arrivals and release points as the PTX skeleton. The producer is a
// single elected thread, as a TMA issuer is. Launch it with
// eg_emu_launch(dim3(1), dim3(32·TotalWarps), PipelineStagesD·HostEmuElems·4,
// kernelName, in, out).
func (s Schedule) EmitHostEmuCUDA(kernelName string, numTiles int) (string, error) {
	return s.emitEmu(kernelName, numTiles, protocol{})
}

func (s Schedule) emitEmu(name string, numTiles int, p protocol) (string, error) {
	if err := s.Check(); err != nil {
		return "", fmt.Errorf("emit host emulation: %w", err)
	}
	if !validName(name) {
		return "", fmt.Errorf("emit host emulation: invalid kernel name %q", name)
	}
	if numTiles <= 0 {
		return "", fmt.Errorf("emit host emulation: %d tiles", numTiles)
	}
	rs := rings(s)
	b := new(strings.Builder)
	w := func(format string, args ...any) { fmt.Fprintf(b, format+"\n", args...) }
	w("constexpr int WS_TILES = %d, WS_E = %d;", numTiles, HostEmuElems)
	parity := "(k / D) & 1"
	if p.parityByIter {
		parity = "k & 1"
	}
	w("template <int D> int ws_parity(int k) { return %s; }", parity)
	w("")
	w("__global__ void %s(const float* in, float* out) {", name)
	w("    float* ring0 = (float*)eg_emu_dynamic_smem();")
	for i, d := range s.RingDepths {
		w("    __shared__ uint64_t full%d[%d], empty%d[%d];", i, d, i, d)
		if i > 0 {
			w("    __shared__ float ring%d[%d * WS_E];", i, d)
		}
	}
	w("    const int tid = threadIdx.x, warp = tid / 32;")
	w("    if (tid == 0) {")
	for i, d := range s.RingDepths {
		w("        for (int s = 0; s < %d; ++s) { eg_emu_mbar_init(&full%d[s], 1); eg_emu_mbar_init(&empty%d[s], 1); }", d, i, i)
	}
	w("    }")
	w("    __syncthreads();")
	for i, r := range s.Roles {
		w("    if (warp >= %d && warp < %d) {", r.FirstWarp, r.FirstWarp+r.Warps)
		w("        const int rtid = tid - %d, rthreads = %d;", 32*r.FirstWarp, 32*r.Warps)
		if i == 0 {
			w("        if (rtid != 0) return;")
		}
		w("        for (int k = 0; k < WS_TILES; ++k) {")
		if i > 0 {
			d := rs[i-1].depth
			w("            eg_emu_mbar_wait(&full%d[k %% %d], ws_parity<%d>(k));", i-1, d, d)
		}
		if i < len(rs) && !(i == 0 && p.skipEmptyWait) {
			d := rs[i].depth
			w("            eg_emu_mbar_wait(&empty%d[k %% %d], ws_parity<%d>(k) ^ 1);", i, d, d)
		}
		switch {
		case i == 0:
			d := rs[0].depth
			w("            eg_emu_mbar_arrive_expect_tx(&full0[k %% %d], WS_E * 4);", d)
			w("            eg_emu_cp_async_bulk(ring0 + (k %% %d) * WS_E, in + k * WS_E, WS_E * 4, &full0[k %% %d]);", d, d)
		default:
			src := fmt.Sprintf("ring%d[(k %% %d) * WS_E + e]", i-1, rs[i-1].depth)
			expr := src
			switch {
			case i == 1:
				expr = "2.0f * " + src
			case i == 2:
				expr = src + " + 1.0f"
			}
			if i < len(rs) {
				w("            for (int e = rtid; e < WS_E; e += rthreads) ring%d[(k %% %d) * WS_E + e] = %s;", i, rs[i].depth, expr)
			} else {
				w("            for (int e = rtid; e < WS_E; e += rthreads) out[k * WS_E + e] = %s;", expr)
			}
			w("            eg_emu_bar_sync(%d, %d);", 1+i, 32*r.Warps)
			w("            if (rtid == 0) {")
			if i < len(rs) {
				w("                eg_emu_mbar_arrive(&full%d[k %% %d]);", i, rs[i].depth)
			}
			for j, rg := range rs {
				if rg.releaser == i {
					w("                eg_emu_mbar_arrive(&empty%d[k %% %d]);", j, rg.depth)
				}
			}
			w("            }")
		}
		w("        }")
		w("        return;")
		w("    }")
	}
	w("}")
	return b.String(), nil
}

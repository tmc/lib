// Command xinventory generates the inventory of hand-written NVIDIA packages.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"strings"
)

func main() {
	root := flag.String("root", "x", "package directory")
	check := flag.Bool("check", false, "check the README without writing it")
	flag.Parse()
	if err := run(*root, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(root string, check bool) error {
	entries, err := os.ReadDir(root)
	if err != nil {
		return err
	}
	var out bytes.Buffer
	out.WriteString("<!-- Code generated by internal/cmd/xinventory; DO NOT EDIT. -->\n\n# nvidia/x\n\nHand-written packages built on the generated NVIDIA bindings.\n\nThis inventory describes the source tree that generated it, not installed\nCUDA libraries or hardware support. Regenerate before relying on it.\nFrom the nvidia module, run `go run ./internal/cmd/xinventory`; use\n`-root` to select another package directory, or `-check` to check for drift.\n\n| Package | Package documentation |\n| --- | --- |\n")
	for _, entry := range entries {
		if !entry.IsDir() || strings.HasPrefix(entry.Name(), ".") {
			continue
		}
		name := entry.Name()
		file, err := parser.ParseFile(token.NewFileSet(), filepath.Join(root, name, "doc.go"), nil, parser.ParseComments)
		if err != nil {
			return fmt.Errorf("read package %s documentation: %w", name, err)
		}
		description, err := summary(file)
		if err != nil {
			return fmt.Errorf("package %s: %w", name, err)
		}
		fmt.Fprintf(&out, "| [%s](%s/) | %s |\n", name, name, strings.ReplaceAll(description, "|", "\\|"))
	}
	path := filepath.Join(root, "README.md")
	if check {
		old, err := os.ReadFile(path)
		if err != nil {
			return err
		}
		if !bytes.Equal(old, out.Bytes()) {
			return fmt.Errorf("%s is stale: run xinventory", path)
		}
		return nil
	}
	return os.WriteFile(path, out.Bytes(), 0644)
}

func summary(file *ast.File) (string, error) {
	if file.Doc == nil {
		return "", fmt.Errorf("missing package comment")
	}
	paragraph, _, _ := strings.Cut(file.Doc.Text(), "\n\n")
	paragraph = strings.Join(strings.Fields(paragraph), " ")
	if i := strings.Index(paragraph, ". "); i >= 0 {
		paragraph = paragraph[:i+1]
	}
	if paragraph == "" {
		return "", fmt.Errorf("empty package comment")
	}
	return paragraph, nil
}

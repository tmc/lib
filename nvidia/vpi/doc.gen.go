// Package vpi provides Go bindings for the NVIDIA Vision Programming Interface (VPI),
// libnvvpi, generated from the VPI 3.2.4 public headers.
//
// The bound surface is context and stream lifecycle, image creation and
// external-buffer wrapping, image locking, and one image operation,
// [Stream.SubmitRescale]. It is not the whole of VPI.
//
// Every call has a plain function form named after the C symbol, such as
// [SubmitRescale], and handle types carry the same calls as methods. The two
// are the same code; the index below names the method form.
//
// # Backends
//
// A backend is queried, never assumed. [Backends] reports the backends the running
// platform actually provides; it does not promise that any particular one is present.
// [BackendPVA], [BackendVIC], [BackendNVENC] and [BackendOFA] exist only on Tegra
// (Jetson) hardware. [BackendCUDA] requires a CUDA-capable GPU and driver. A call
// that succeeds on [BackendCPU] establishes nothing about any other backend.
//
// # Ownership
//
// [Image], [Stream], [Context], [Event], [Array], [Pyramid] and [Payload] are opaque
// library handles. Each is owned by the context that was current when it was created,
// and must be destroyed before that context is destroyed.
//
// Memory wrapped by [ImageCreateWrapper] is caller-owned for the entire lifetime of the
// wrapper, not merely for the duration of one submission: VPI never copies it and never
// frees it. The caller must keep it alive and unmoved until after the wrapper is
// destroyed and every stream that touched it has synchronized. Go heap memory does not
// satisfy that contract on its own; see [ImageCreateWrapper] for the rules.
//
// Submissions are asynchronous. A submission such as [Stream.SubmitRescale] returns once
// the operation is queued, not once it has run. Every input and output image must
// stay valid, and must not be unlocked out from under the library, until
// [Stream.Sync] returns.
//
// # Platform
//
// These bindings are generated from the arm64 (Jetson/L4T) VPI 3.2.4 package and are
// built for linux only. The ABI is LP64. No part of this package has been executed
// against a VPI runtime by its author; see the package tests for what is and is not
// checked without hardware.
//
// # Contexts
//
//   - [NewContext]: Create a context instance.
//   - [Context.Destroy]: Destroy a context instance as well as all resources it owns.
//   - [ContextGetCurrent]: Gets the context for the calling thread.
//   - [Context.GetFlags]: Get the current context flags.
//   - [ContextPop]: Pops a context from a per-thread context stack and saves it to the ctx variable.
//   - [Context.Push]: Pushes the context to a per-thread context stack and sets this context as the current context for the calling thread.
//   - [Context.SetCurrent]: Sets the context for the calling thread.
//
// # Library
//
//   - [GetLastStatus]: Returns and resets the status of the last VPI function call in current thread.
//   - [GetVersion]: Retrieves the library's version number.
//   - [Payload.Destroy]: Deallocates the payload object and all associated resources.
//   - [Payload.GetFlags]: Returns the flags associated with a payload.
//   - [PeekAtLastStatus]: Returns the status of the last VPI function call in current thread.
//
// # Images
//
//   - [NewImage]: Create an empty image instance with the specified flags.
//   - [Image.CreateView]: Create an image that wraps an axis-aligned rectangular sub-region of an existing image.
//   - [Image.Destroy]: Destroy an image instance.
//   - [Image.GetFlags]: Get the image flags.
//   - [Image.GetFormat]: Get the image format.
//   - [Image.GetSize]: Get the image dimensions in pixels.
//   - [Image.Lock]: Acquires the lock on an image object.
//   - [Image.SetView]: Redefines the image view position inside a parent image.
//   - [Image.Unlock]: Releases the lock on an image object.
//
// # Streams
//
//   - [NewStream]: Create a stream instance.
//   - [Stream.Destroy]: Destroy a stream instance and deallocate all HW resources.
//   - [Stream.Flush]: Submits all pending operations for execution.
//   - [Stream.GetFlags]: Gets the [Stream] flags passed during its creation.
//   - [Stream.Sync]: Blocks the calling thread until all submitted commands in this stream queue are done (queue is empty).
//   - [Stream.WaitEvent]: Pushes a command that blocks the processing of all future commands submitted to the stream until the event is signaled.
//
// # Operations
//
//   - [Stream.SubmitRescale]: Changes the size and scale of a 2D image.
//
// [VPI 3.2 reference]: https://docs.nvidia.com/vpi/3.2/index.html

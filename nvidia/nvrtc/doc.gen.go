// Package nvrtc provides low-level Go bindings for NVIDIA Runtime Compilation (NVRTC).
//
// NVRTC compiles CUDA C++ source code to PTX, cubin, or LTO-IR at runtime,
// enabling just-in-time kernel compilation without a separate nvcc invocation.
//
// The central type is [Program]. Create one with [CreateProgram], compile with
// [Program.Compile], and retrieve output with [Program.GetPTX] or [Program.GetCUBIN].
// Clean up with [DestroyProgram].
//
// This package maps every function from nvrtc.h to a Go function using
// [github.com/ebitengine/purego] for cgo-free dynamic loading of libnvrtc.
// All functions return errors wrapping nvrtcResult with descriptive messages
// from nvrtcGetErrorString.
//
// # Name Expressions
//
//   - [Program.AddNameExpression]: [Program.AddNameExpression] notes the given name expression denoting the address of a global function or device/__constant__ variable.
//   - [Program.GetLoweredName]: [Program.GetLoweredName] extracts the lowered (mangled) name for a global function or device/__constant__ variable, and updates *lowered_name to point to it.
//
// # Compilation
//
//   - [Program.Compile]: [Program.Compile] compiles the given program.
//
// # Program Management
//
//   - [CreateProgram]: [CreateProgram] creates an instance of [Program] with the given input parameters, and sets the output parameter prog with it.
//   - [DestroyProgram]: [DestroyProgram] destroys the given program.
//
// # Output Retrieval
//
//   - [Program.GetCUBIN]: [Program.GetCUBIN] stores the cubin generated by the previous compilation of prog in the memory pointed by cubin.
//   - [Program.GetCUBINSize]: [Program.GetCUBINSize] sets the value of cubinSizeRet with the size of the cubin generated by the previous compilation of prog.
//   - [Program.GetLTOIR]: [Program.GetLTOIR] stores the LTO IR generated by the previous compilation of prog in the memory pointed by LTOIR.
//   - [Program.GetLTOIRSize]: [Program.GetLTOIRSize] sets the value of LTOIRSizeRet with the size of the LTO IR generated by the previous compilation of prog.
//   - [Program.GetOptiXIR]: [Program.GetOptiXIR] stores the OptiX IR generated by the previous compilation of prog in the memory pointed by optixir.
//   - [Program.GetOptiXIRSize]: [Program.GetOptiXIRSize] sets the value of optixirSizeRet with the size of the OptiX IR generated by the previous compilation of prog.
//   - [Program.GetPTX]: [Program.GetPTX] stores the PTX generated by the previous compilation of prog in the memory pointed by ptx.
//   - [Program.GetPTXSize]: [Program.GetPTXSize] sets the value of ptxSizeRet with the size of the PTX generated by the previous compilation of prog (including the trailing NULL).
//   - [Program.GetProgramLog]: [Program.GetProgramLog] stores the log generated by the previous compilation of prog in the memory pointed by log.
//   - [Program.GetProgramLogSize]: [Program.GetProgramLogSize] sets logSizeRet with the size of the log generated by the previous compilation of prog (including the trailing NULL).
//   - [Program.GetTileIR]: [Program.GetTileIR] stores the cuda_tile IR generated by the previous compilation of prog in the memory pointed by TileIR.
//   - [Program.GetTileIRSize]: [Program.GetTileIRSize] sets the value of TileIRSizeRet with the size of the cuda_tile IR generated by the previous compilation of prog.
//
// # Architecture Queries
//
//   - [GetNumSupportedArchs]: [GetNumSupportedArchs] sets the output parameter numArchs with the number of architectures supported by NVRTC.
//   - [GetSupportedArchs]: [GetSupportedArchs] populates the array passed via the output parameter supportedArchs with the architectures supported by NVRTC.
//
// # Version Queries
//
//   - [Version]: [Version] sets the output parameters major and minor with the CUDA Runtime Compilation version number.
//
// # Other
//
//   - [Program.GetPCHCreateStatus]: returns the PCH creation status.
//   - [GetPCHHeapSize]: retrieve the current size of the PCH Heap.
//   - [Program.GetPCHHeapSizeRequired]: retrieve the required size of the PCH heap required to compile the given program.
//   - [SetPCHHeapSize]: set the size of the PCH Heap.
//

// Package ncclep provides Go bindings for the NCCL expert-parallel communication library, libnccl_ep.
//
// Communicators, streams, windows, data types, and result codes use the types in
// [github.com/tmc/lib/nvidia/nccl]. This package loads and probes libnccl_ep independently of NCCL.
//
// Initialize public descriptors with their New functions before setting workload fields.
// Their zero values do not contain the required ABI size and magic fields.
// Configuration defaults alone do not define a valid workload: set the group dimensions
// and choose an explicit handle layout before creating handles.
//
// Device storage, tensor descriptors, callbacks, and asynchronous input arrays are caller-owned.
// Keep them valid until the operation completes. Pin any Go memory retained by C, including
// nested pointers, for the full retention interval. A uintptr does not keep an allocation alive.
// MaskQuery writes a device array; MaskUpdate reads a host array asynchronously.
//
// See the [NCCL EP reference] for collective ordering and supported algorithms.
//
// # Operations
//
//   - [Handle.Combine]: combines expert outputs in the original token order.
//   - [Handle.Complete]: completes a staged EP operation on the given stream.
//   - [Handle.Dispatch]: dispatches tokens to experts using the handle's routing metadata.
//   - [GetVersion]: returns the EP library version code.
//
// # Groups and handles
//
//   - [NewGroup]: collectively creates an EP group from an NCCL communicator.
//   - [Group.CreateHandle]: creates a handle and updates its routing metadata.
//   - [Group.Destroy]: destroys an EP group.
//   - [Handle.Destroy]: destroys a handle without freeing caller-owned storage.
//   - [Group.MemSize]: returns the required caller-owned handle storage size in bytes.
//   - [Group.InitHandle]: initializes a handle for an explicit layout.
//   - [Handle.Update]: updates a handle's routing metadata on the given stream.
//
// # Failure handling
//
//   - [Group.ErrorClear]: clears the group's asynchronous error flag.
//   - [Group.GetAsyncError]: reads the asynchronous error flag without synchronizing the GPU.
//   - [Group.MaskClean]: collectively cleans masked-rank communication state.
//   - [Group.MaskQuery]: copies the rank mask to a device array asynchronously.
//   - [Group.MaskUpdate]: copies a host rank mask to the device asynchronously.
//
// # Tensor descriptors
//
//   - [TensorAlloc]: allocates a tensor descriptor and copies its dimensions.
//   - [TensorDestroy]: releases a descriptor returned by TensorAlloc.
//

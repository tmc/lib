// Package cudss provides Go bindings for the NVIDIA cuDSS direct sparse solver, libcudss.
//
// A solve runs as a sequence of phases against one library handle: analysis,
// factorization, then solve. Execute takes the phase, a Config, a Data object,
// the system matrix, the solution and the right-hand side.
//
// Configuration and data parameters are read and written through the typed
// accessors on Config and Data. The underlying C entry points take a void
// pointer and a caller-supplied byte count, and the library trusts the count;
// the typed accessors derive it from the Go value so a mismatched size cannot
// be spelled.
//
// Ownership. Matrix objects borrow: cudssMatrixCreateCsr and cudssMatrixCreateDn
// record the device addresses handed to them and do not copy. Those allocations,
// and the Matrix objects themselves, must stay live and unmodified from the
// analysis phase through completion of the last solve that uses them. Execute is
// asynchronous with respect to the host: it returns once the work is enqueued on
// the handle's stream, so "completion" means the stream has been synchronized,
// not that Execute returned. Destroying a Matrix, freeing its device memory, or
// reusing the buffers before that point is a use-after-free the library cannot
// detect.
//
// Config and Data objects are owned by the caller and must outlive every Execute
// that names them. Data holds the factorization; it is bound to the handle it was
// created from.
//
// Parameter accessors do not borrow. A Go slice passed to a Set accessor is read
// during the call and copied by cuDSS, so it may be reused or collected as soon
// as the call returns; a slice passed to a Get accessor is written during the
// call and not retained. The one exception is Data.SetUserHostInterrupt, which
// takes an address the library keeps and polls from its own threads: that
// address must not be Go memory, and must stay valid until the phases that use
// it have completed.
//
// A LogFunc installed with SetLogFunc is retained until it is replaced, and is
// called on a thread owned by libcudss.
//
// This package loads libcudss lazily and independently. Importing it does not open
// the library; the first call does. A symbol absent from the installed version
// reports *SymbolError rather than panicking.
//
// Multi-GPU and multi-node setup APIs are bound; distributed execution requires
// a compatible communication layer and topology. See the [cuDSS documentation].
//

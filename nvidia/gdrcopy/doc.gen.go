// Package gdrcopy provides Go bindings for GDRCopy's libgdrapi, NVIDIA's
// user-space interface to the gdrdrv kernel module for mapping GPU memory
// into a process's address space.
//
// Pin device memory with [Handle.PinBuffer], map it with [Handle.Map], and
// move bytes with [MemHandle.CopyToMapping] and [MemHandle.CopyFromMapping].
//
// # Release order
//
// gdrapi.h requires releases in the reverse of the order they were taken:
// unmap before unpin, unpin before close. Unpinning a mapped handle leaves
// the process holding an mmap of an aperture the driver has released, which
// the library does not detect. This package tracks what it created and
// returns [ErrMapped] rather than making the call, so the order is enforced
// for handles obtained through it. [Handle.Close] is the one relaxation:
// gdr_close unpins whatever is left, so pinned-but-unmapped handles need no
// unpinning first, but a live mapping still refuses the close.
//
// # Alignment and offsets
//
// The kernel module pins whole GPU pages. It aligns the address down to
// [GPUPageSize] and rounds the length up, so a pinning generally begins
// below the address that was pinned and a mapping begins at that lower
// address. [Handle.Map] returns the base of the mapping, not the address of
// the caller's data: read [Info.Va] from [Handle.GetInfoV2] and use
// [Info.Offset] to find where the data starts inside it.
//
// # Mappings are not memory
//
// The address [Handle.Map] returns is an mmap of a device aperture. Do not
// build a Go slice on it and do not load or store through it directly.
// [MemHandle.CopyToMapping] and [MemHandle.CopyFromMapping] run the
// per-architecture copy paths libgdrapi implements for these mappings and
// issue the fences they require. Neither orders the copy against GPU work
// already launched.
//
// # Errors
//
// gdrcopy has no status enum. Its calls return POSIX error numbers, which
// this package reports as [*Error] wrapping a syscall.Errno, so errors.Is
// works against the errno directly. When libgdrapi is absent, or is older
// than a symbol being called, every entry point returns an error
// ([*LibraryError] or [*SymbolError]) rather than panicking or reporting a
// success it did not have.
//
// # Requirements
//
// Linux, libgdrapi.so.2 on the loader path (or named by GDRCOPY_LIB_PATH),
// and either the gdrdrv kernel module or a CUDA driver whose device
// supports dma-buf mmap. [Open] reports [ErrOpen] when it has neither.
//
// These bindings were generated from the gdrapi.h of the release linked
// below, which cmd/gen-gdrcopy vendors and pins.
//
// [GDRCopy documentation]: https://github.com/NVIDIA/gdrcopy/tree/93c606bbcaa10457cbbab93163aa446d902b983d

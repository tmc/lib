type upstreamManifest struct {
	SchemaVersion int `json:"schema_version"`
	Packages      map[string]struct {
		Generation struct {
			Outputs []upstreamOutput `json:"outputs"`
		} `json:"generation"`
	} `json:"packages"`
}

type upstreamOutput struct {
	Path   string `json:"path"`
	SHA256 string `json:"sha256"`
}

// checkUpstream checks only recorded outputs, not generator or runtime behavior.
func checkUpstream(root string, data []byte) error {
	var manifest upstreamManifest
	if err := json.Unmarshal(data, &manifest); err != nil {
		return err
	}
	if manifest.SchemaVersion != 1 || len(manifest.Packages) == 0 {
		return fmt.Errorf("unsupported or empty provenance manifest")
	}
	for name, pkg := range manifest.Packages {
		if name == "." || name == ".." || path.Base(name) != name || strings.Contains(name, `\`) {
			return fmt.Errorf("invalid package %q", name)
		}
		if len(pkg.Generation.Outputs) == 0 {
			return fmt.Errorf("%s: no recorded outputs", name)
		}
		expected := make(map[string]bool)
		for _, output := range pkg.Generation.Outputs {
			prefix := "nvidia/" + name + "/"
			if !strings.HasPrefix(output.Path, prefix) {
				return fmt.Errorf("%s: output outside package: %q", name, output.Path)
			}
			file := strings.TrimPrefix(output.Path, prefix)
			if file == "" || file == "." || file == ".." || path.Base(file) != file || strings.Contains(file, `\`) {
				return fmt.Errorf("invalid output %q", output.Path)
			}
			if expected[file] {
				return fmt.Errorf("duplicate output %q", output.Path)
			}
			expected[file] = true
			digest, err := hex.DecodeString(output.SHA256)
			if err != nil || len(digest) != sha256.Size {
				return fmt.Errorf("invalid SHA256 for %s", output.Path)
			}
			contents, err := os.ReadFile(filepath.Join(root, name, file))
			if err != nil {
				return fmt.Errorf("%s: %w", output.Path, err)
			}
			got := sha256.Sum256(contents)
			if hex.EncodeToString(got[:]) != strings.ToLower(output.SHA256) {
				return fmt.Errorf("%s: SHA256 mismatch", output.Path)
			}
		}
		files, err := os.ReadDir(filepath.Join(root, name))
		if err != nil {
			return err
		}
		for _, file := range files {
			if file.IsDir() || !strings.HasSuffix(file.Name(), ".go") {
				continue
			}
			generated := strings.HasSuffix(file.Name(), ".gen.go")
			if !generated {
				f, err := parser.ParseFile(token.NewFileSet(), filepath.Join(root, name, file.Name()), nil, parser.PackageClauseOnly|parser.ParseComments)
				if err != nil {
					return err
				}
				generated = ast.IsGenerated(f)
			}
			if generated && !expected[file.Name()] {
				return fmt.Errorf("%s/%s: unrecorded generated file", name, file.Name())
			}
		}
	}
	return nil
}

func TestUpstreamOutputs(t *testing.T) {
	data, err := os.ReadFile("upstream.json")
	if err != nil {
		t.Fatal(err)
	}
	if err := checkUpstream(".", data); err != nil {
		t.Fatal(err)
	}
}

func TestUpstreamOutputMutations(t *testing.T) {
	const source = "// Code generated by fixture. DO NOT EDIT.\n\npackage fixture\n"
	hash := sha256.Sum256([]byte(source))
	data := []byte(fmt.Sprintf(`{"schema_version":1,"packages":{"fixture":{"generation":{"outputs":[{"path":"nvidia/fixture/types.gen.go","sha256":"%x"}]}}}}`, hash))
	for _, name := range []string{"unchanged", "modified", "missing", "extra suffix", "extra marker", "maintained"} {
		t.Run(name, func(t *testing.T) {
			root := t.TempDir()
			dir := filepath.Join(root, "fixture")
			if err := os.Mkdir(dir, 0700); err != nil {
				t.Fatal(err)
			}
			write := func(name, body string) {
				t.Helper()
				if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0600); err != nil {
					t.Fatal(err)
				}
			}
			write("types.gen.go", source)
			switch name {
			case "modified":
				write("types.gen.go", source+"// changed\n")
			case "missing":
				if err := os.Remove(filepath.Join(dir, "types.gen.go")); err != nil {
					t.Fatal(err)
				}
			case "extra suffix":
				write("extra.gen.go", "package fixture\n")
			case "extra marker":
				write("loader_test.go", source)
			case "maintained":
				write("example_test.go", "package fixture\n")
			}
			err := checkUpstream(root, data)
			wantErr := name != "unchanged" && name != "maintained"
			if (err != nil) != wantErr {
				t.Fatalf("check=%v, want error=%v", err, wantErr)
			}
		})
	}
}

// isGenerated reports whether the file at path is machine-generated, by the
// same rule checkUpstream applies: the .gen.go suffix, or the generated-code
// marker ahead of the package clause.
func isGenerated(path string) (bool, error) {
	if strings.HasSuffix(path, ".gen.go") {
		return true, nil
	}
	f, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.PackageClauseOnly|parser.ParseComments)
	if err != nil {
		return false, err
	}
	return ast.IsGenerated(f), nil
}

// TestUpstreamCoverage checks that every package directory holding generated
// files appears in the manifest. checkUpstream walks the manifest, not the
// tree, so a package that is never recorded is not caught by it: its files are
// pinned by nothing and drift silently. This walks the tree instead.
func TestUpstreamCoverage(t *testing.T) {
	data, err := os.ReadFile("upstream.json")
	if err != nil {
		t.Fatal(err)
	}
	var manifest upstreamManifest
	if err := json.Unmarshal(data, &manifest); err != nil {
		t.Fatal(err)
	}
	entries, err := os.ReadDir(".")
	if err != nil {
		t.Fatal(err)
	}
	for _, entry := range entries {
		if !entry.IsDir() || entry.Name() == "internal" || entry.Name() == "x" {
			continue
		}
		files, err := os.ReadDir(entry.Name())
		if err != nil {
			t.Fatal(err)
		}
		for _, file := range files {
			if file.IsDir() || !strings.HasSuffix(file.Name(), ".go") {
				continue
			}
			generated, err := isGenerated(filepath.Join(entry.Name(), file.Name()))
			if err != nil {
				t.Fatal(err)
			}
			if !generated {
				continue
			}
			if _, ok := manifest.Packages[entry.Name()]; !ok {
				t.Errorf("%s holds generated files but has no upstream.json entry", entry.Name())
			}
			break
		}
	}
}

// coverageManifest reads the self-describing coverage block, which
// checkUpstream ignores. The block restates what the manifest holds, so it can
// disagree with the packages it summarizes: ncclep and ncclm2n were added to
// packages while coverage still counted 33 directories and 28 recorded argv,
// and every existing test stayed green.
type coverageManifest struct {
	Coverage struct {
		Packages     []string `json:"packages"`
		RecordedArgv int      `json:"recorded_argv"`
		MissingArgv  []string `json:"missing_argv"`
	} `json:"coverage"`
	Packages map[string]struct {
		Generation struct {
			Argv []string `json:"argv"`
		} `json:"generation"`
	} `json:"packages"`
}

// checkCoverage reports whether the coverage block agrees with the packages it
// summarizes. It compares the block against the manifest, not against the tree:
// TestUpstreamCoverage already ties the tree to packages.
func checkCoverage(data []byte) error {
	var manifest coverageManifest
	if err := json.Unmarshal(data, &manifest); err != nil {
		return err
	}
	if len(manifest.Packages) == 0 {
		return fmt.Errorf("empty provenance manifest")
	}
	var names, missing []string
	for name, pkg := range manifest.Packages {
		names = append(names, name)
		if len(pkg.Generation.Argv) == 0 {
			missing = append(missing, name)
		}
	}
	sort.Strings(names)
	sort.Strings(missing)
	covered := append([]string(nil), manifest.Coverage.Packages...)
	sort.Strings(covered)
	if !slices.Equal(covered, names) {
		return fmt.Errorf("coverage lists %d packages, manifest has %d: %v", len(covered), len(names), symmetricDifference(covered, names))
	}
	listed := append([]string(nil), manifest.Coverage.MissingArgv...)
	sort.Strings(listed)
	if !slices.Equal(listed, missing) {
		return fmt.Errorf("coverage missing_argv is %v, manifest has %v", listed, missing)
	}
	if want := len(names) - len(missing); manifest.Coverage.RecordedArgv != want {
		return fmt.Errorf("coverage recorded_argv is %d, manifest has %d", manifest.Coverage.RecordedArgv, want)
	}
	return nil
}

// symmetricDifference names the packages on one side only, so a failure says
// which package drifted rather than only that two counts differ.
func symmetricDifference(a, b []string) []string {
	in := make(map[string]int)
	for _, s := range a {
		in[s] |= 1
	}
	for _, s := range b {
		in[s] |= 2
	}
	var only []string
	for s, mask := range in {
		if mask != 3 {
			only = append(only, s)
		}
	}
	sort.Strings(only)
	return only
}

func TestUpstreamCoverageAgreement(t *testing.T) {
	data, err := os.ReadFile("upstream.json")
	if err != nil {
		t.Fatal(err)
	}
	if err := checkCoverage(data); err != nil {
		t.Fatal(err)
	}
}

func TestUpstreamCoverageMutations(t *testing.T) {
	const manifest = `{"coverage":{"packages":["a","b"],"recorded_argv":1,"missing_argv":["b"]},` +
		`"packages":{"a":{"generation":{"argv":["gen"]}},"b":{"generation":{"argv":null}}}}`
	for _, tt := range []struct {
		name    string
		data    string
		wantErr bool
	}{
		{"agreeing", manifest, false},
		{"unlisted package", `{"coverage":{"packages":["a"],"recorded_argv":1,"missing_argv":[]},` +
			`"packages":{"a":{"generation":{"argv":["gen"]}},"b":{"generation":{"argv":["gen"]}}}}`, true},
		{"stale count", `{"coverage":{"packages":["a","b"],"recorded_argv":2,"missing_argv":["b"]},` +
			`"packages":{"a":{"generation":{"argv":["gen"]}},"b":{"generation":{"argv":null}}}}`, true},
		{"wrong gap list", `{"coverage":{"packages":["a","b"],"recorded_argv":1,"missing_argv":["a"]},` +
			`"packages":{"a":{"generation":{"argv":["gen"]}},"b":{"generation":{"argv":null}}}}`, true},
		{"empty manifest", `{"coverage":{"packages":[],"recorded_argv":0,"missing_argv":[]},"packages":{}}`, true},
	} {
		t.Run(tt.name, func(t *testing.T) {
			err := checkCoverage([]byte(tt.data))
			if (err != nil) != tt.wantErr {
				t.Fatalf("check=%v, want error=%v", err, tt.wantErr)
			}
		})
	}
}

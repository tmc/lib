// Package nvcomp provides Go bindings for the batched LZ4 entry points of the NVIDIA nvCOMP library, libnvcomp.
//
// The batched LZ4 API is the low-level interface: it compresses and decompresses
// independent chunks with no container format, no checksum and no metadata. A caller
// is responsible for recording how many chunks there were and how large each one was.
//
// The documentation on each function and parameter is derived from NVIDIA's nvcomp/lz4.h.
// Where it recommends a chunk size, or says that an alignment above the minimum may help,
// that is the vendor's claim carried across as written. Nothing in this package has been
// measured, and this package makes no claim about the throughput or latency of anything.
// See the [nvCOMP low-level API reference] for NVIDIA's own documentation of these calls.
//
// # Device memory
//
// Every argument named with a Device prefix is an address in device memory, and the
// types are distinct so that a host address cannot reach one by accident. In
// particular [DevicePointerArray] is the device address of an array of device
// pointers: the array itself has to live in device memory, not only the buffers it
// points at. Passing a host array where a [DevicePointerArray] is expected is not a
// Go type error at the conversion site, so construct these values only from a device
// allocation.
//
// This package does not allocate, free or copy device memory, and does not depend on
// a CUDA package to do so. Obtain addresses from whichever CUDA binding the program
// already uses and convert them at the call.
//
// # Asynchronous completion
//
// CompressAsync, DecompressAsync and GetDecompressSizeAsync enqueue work on a stream
// and return as soon as the launch is accepted. A nil error from one of them means
// the launch was accepted; it does not mean the work ran, and it does not mean the
// work succeeded. Until the stream is synchronized, every buffer passed in must stay
// live and unmodified: the temporary workspace, the input chunks, the output chunks,
// the size arrays and the status array.
//
// After the stream completes, read the per-chunk status array. A chunk that failed
// reports its own status there and nowhere else. The host-side return value cannot
// report it. Passing zero for the status array disables per-chunk reporting, which
// means failures become silently wrong output.
//
// # Options
//
// [CompressOpts] and [DecompressOpts] are passed to the library by value. Their zero
// values equal the vendor defaults nvcompBatchedLZ4CompressDefaultOpts and
// nvcompBatchedLZ4DecompressDefaultOpts, so a zero value is usable. The Reserved
// field must stay zero; the library documents those bytes as reserved for future
// fields.
//
// The same options value must be given to every call in one operation. The temporary
// size, the alignment requirements and the maximum output size are all derived from
// it, and a mismatch between the sizing call and the compression call is undefined
// behavior in the C API rather than a reported error.
//
// # Compression
//
//   - [CompressAsync]: Perform batched asynchronous compression.
//   - [CompressGetMaxOutputChunkSize]: Get the maximum size that a chunk of size at most max_uncompressed_chunk_bytes could compress to.
//   - [CompressGetRequiredAlignments]: Get the minimum buffer alignment requirements for compression.
//   - [CompressGetTempSizeAsync]: Get the amount of temporary memory required on the GPU for compression asynchronously.
//   - [CompressGetTempSizeSync]: Get the amount of temporary memory required on the GPU for compression synchronously.
//
// # Decompression
//
//   - [DecompressAsync]: Perform batched asynchronous decompression.
//   - [DecompressGetRequiredAlignments]: Get the minimum buffer alignment requirements for decompression.
//   - [DecompressGetTempSizeAsync]: Get the amount of temporary memory required on the GPU for decompression asynchronously.
//   - [DecompressGetTempSizeSync]: Get the amount of temporary memory required on the GPU for decompression synchronously.
//   - [GetDecompressSizeAsync]: Asynchronously compute the number of bytes of uncompressed data for each compressed chunk.
//
// # Library
//
//   - [GetProperties]: Retrieve the nvCOMP library properties.
//   - [GetStatusString]: Returns the description string for an error code.
//
// [nvCOMP low-level API reference]: https://docs.nvidia.com/cuda/nvcomp/

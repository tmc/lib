// CodegenOptions configures Metal Shading Language (MSL) compute shader code generation.
type CodegenOptions struct {
	KernelName string
	Precision  string // "float", "half"
	UseMMA     bool   // Request simdgroup_matrix code generation.
	Registry   *OperatorRegistry
}


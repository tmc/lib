func validMSLIdentifier(name string) bool {
	if name == "" {
		return false
	}
	if _, reserved := mslReservedWords[name]; reserved {
		return false
	}
	for i, r := range name {
		valid := r == '_' || r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z'
		if i > 0 {
			valid = valid || r >= '0' && r <= '9'
		}
		if !valid {
			return false
		}
	}
	return true
}

// GenerateMSL generates a complete, compilable Metal Shading Language compute kernel from an extracted AST Expr.
func GenerateMSL(expr *Expr, opts CodegenOptions) (string, error) {
	if expr == nil {
		return "", fmt.Errorf("egraph: nil expr passed to GenerateMSL")
	}
	if opts.KernelName == "" {
		opts.KernelName = "GeneratedMSLMegakernel"
	}
	if opts.Precision == "" {
		opts.Precision = "float"
	}
	if opts.Precision != "float" && opts.Precision != "half" {
		return "", fmt.Errorf("egraph: unsupported MSL precision %q", opts.Precision)
	}
	if !validMSLIdentifier(opts.KernelName) {
		return "", fmt.Errorf("egraph: invalid MSL kernel name %q", opts.KernelName)
	}

	var sb strings.Builder

	sb.WriteString("// Auto-generated by apple/x/metal/egraph\n")
	sb.WriteString("#include <metal_stdlib>\n")
	sb.WriteString("using namespace metal;\n\n")

	sb.WriteString(fmt.Sprintf(`// Intra-SIMD reduction helper using Apple Silicon 32-wide SIMD-groups
inline %s simdgroup_sum(%s val) {
    #pragma unroll
    for (ushort offset = 16; offset > 0; offset /= 2) {
        val += simd_shuffle_down(val, offset);
    }
    return val;
}

`, opts.Precision, opts.Precision))

	if opts.Registry != nil {
		definition, ok := opts.Registry.lookup(expr.Op)
		if !ok {
			return "", fmt.Errorf("egraph: operator %q is not registered", expr.Op)
		}
		if err := validateExprTree(expr, opts.Registry); err != nil {
			return "", err
		}
		if definition.MSL != nil {
			kernel, err := definition.MSL(expr, opts)
			if err != nil {
				return "", err
			}
			sb.WriteString(kernel)
			return sb.String(), nil
		}
		if !isBuiltinMSLOperator(expr.Op) {
			return "", fmt.Errorf("egraph: registered operator %q has no MSL code generator", expr.Op)
		}
	}
	if opts.UseMMA {
		return "", fmt.Errorf("egraph: simdgroup_matrix code generation is not implemented")
	}

	switch expr.Op {
	case "fused_swiglu_gemv":
		sb.WriteString(generateMSLSwiGLUKernel(opts))
	case "fused_rmsnorm_gemv":
		sb.WriteString(generateMSLRMSNormGEMVKernel(opts))
	case "fused_rope_store_kv":
		sb.WriteString(generateMSLRoPEStoreKVKernel(opts))
	case "add", "mul", "silu":
		kernel, err := generateMSLElementwiseKernel(expr, opts)
		if err != nil {
			return "", err
		}
		sb.WriteString(kernel)
	default:
		return "", fmt.Errorf("egraph: no MSL code generator for %s", expr.Op)
	}

	return sb.String(), nil
}

func validateExprSignature(expr *Expr, signatures []OperatorSignature) error {
	for _, signature := range signatures {
		if signature.Result != expr.Sort || len(signature.Children) != len(expr.Children) {
			continue
		}
		matches := true
		for i, want := range signature.Children {
			if expr.Children[i] == nil || want != "" && expr.Children[i].Sort != want {
				matches = false
				break
			}
		}
		if matches {
			return nil
		}
	}
	return fmt.Errorf("egraph: expression %q does not match a registered signature", expr.Op)
}

func validateExprTree(root *Expr, registry *OperatorRegistry) error {
	visited := make(map[*Expr]bool)
	active := make(map[*Expr]bool)
	var visit func(*Expr) error
	visit = func(expr *Expr) error {
		if expr == nil {
			return fmt.Errorf("egraph: nil child in registered expression")
		}
		if active[expr] {
			return fmt.Errorf("egraph: cyclic expression at operator %q", expr.Op)
		}
		if visited[expr] {
			return nil
		}
		definition, ok := registry.lookup(expr.Op)
		if !ok {
			if len(expr.Children) != 0 {
				return fmt.Errorf("egraph: expression operator %q is not registered", expr.Op)
			}
		} else if err := validateExprSignature(expr, definition.Signatures); err != nil {
			return err
		}
		active[expr] = true
		for _, child := range expr.Children {
			if err := visit(child); err != nil {
				return err
			}
		}
		delete(active, expr)
		visited[expr] = true
		return nil
	}
	return visit(root)
}

func isBuiltinMSLOperator(op string) bool {
	switch op {
	case "fused_swiglu_gemv", "fused_rmsnorm_gemv", "fused_rope_store_kv", "add", "mul", "silu":
		return true
	default:
		return false
	}
}

func generateMSLSwiGLUKernel(opts CodegenOptions) string {
	return fmt.Sprintf(`kernel void %s(
    device const %s* x                 [[buffer(0)]],
    device const %s* W_gate            [[buffer(1)]],
    device const %s* W_up              [[buffer(2)]],
    device const %s* W_down            [[buffer(3)]],
    device %s* out                     [[buffer(4)]],
    constant uint& hidden_dim          [[buffer(5)]],
    constant uint& intermediate_dim    [[buffer(6)]],
    threadgroup %s* s_act              [[threadgroup(0)]],
    uint row                           [[threadgroup_position_in_grid]],
    uint tid                           [[thread_position_in_threadgroup]],
    uint simd_lane                     [[thread_index_in_simdgroup]],
    uint simd_id                       [[simdgroup_index_in_threadgroup]]
) {
    // 1. Compute intermediate Gate & Up GEMVs + SiLU activation in parallel
    for (uint j = tid; j < intermediate_dim; j += 128) {
        %s gate = 0.0f;
        %s up = 0.0f;
        for (uint k = 0; k < hidden_dim; k++) {
            gate += x[k] * W_gate[j * hidden_dim + k];
            up += x[k] * W_up[j * hidden_dim + k];
        }
        %s silu = gate / (1.0f + exp(-gate));
        s_act[j] = silu * up;
    }
    threadgroup_barrier(mem_flags::mem_threadgroup);

    // 2. Down projection GEMV with SIMD-group reductions
    if (row < hidden_dim) {
        device const %s* w_row = W_down + row * intermediate_dim;
        %s acc = 0.0f;
        for (uint j = tid; j < intermediate_dim; j += 128) {
            acc += s_act[j] * w_row[j];
        }
        acc = simdgroup_sum(acc);
        threadgroup float s_sum[4];
        if (simd_lane == 0) s_sum[simd_id] = acc;
        threadgroup_barrier(mem_flags::mem_threadgroup);

        %s block_sum = (simd_id == 0 && simd_lane < 4) ? s_sum[simd_lane] : 0.0f;
        if (simd_id == 0) block_sum = simdgroup_sum(block_sum);
        if (tid == 0) out[row] = block_sum;
    }
}
`, opts.KernelName, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision)
}

func generateMSLRMSNormGEMVKernel(opts CodegenOptions) string {
	return fmt.Sprintf(`kernel void %s(
    device const %s* x                 [[buffer(0)]],
    device const %s* weight            [[buffer(1)]],
    device const %s* W_proj            [[buffer(2)]],
    device %s* out                     [[buffer(3)]],
    constant uint& dim                 [[buffer(4)]],
    constant uint& out_dim             [[buffer(5)]],
    constant float& eps                [[buffer(6)]],
    uint row                           [[threadgroup_position_in_grid]],
    uint tid                           [[thread_position_in_threadgroup]],
    uint simd_lane                     [[thread_index_in_simdgroup]],
    uint simd_id                       [[simdgroup_index_in_threadgroup]]
) {
    // 1. RMSNorm reduction over dimension
    %s local_sq = 0.0f;
    for (uint i = tid; i < dim; i += 128) {
        %s v = x[i];
        local_sq += v * v;
    }
    local_sq = simdgroup_sum(local_sq);
    threadgroup float s_sum[4];
    if (simd_lane == 0) s_sum[simd_id] = local_sq;
    threadgroup_barrier(mem_flags::mem_threadgroup);

    %s total_sq = (simd_id == 0 && simd_lane < 4) ? s_sum[simd_lane] : 0.0f;
    if (simd_id == 0) total_sq = simdgroup_sum(total_sq);

    threadgroup float s_rms;
    if (tid == 0) {
        s_rms = rsqrt(total_sq / float(dim) + eps);
    }
    threadgroup_barrier(mem_flags::mem_threadgroup);

    // 2. Linear projection GEMV
    if (row < out_dim) {
        device const %s* w_row = W_proj + row * dim;
        %s acc = 0.0f;
        for (uint i = tid; i < dim; i += 128) {
            %s norm_x = (x[i] * s_rms) * weight[i];
            acc += norm_x * w_row[i];
        }
        acc = simdgroup_sum(acc);
        if (simd_lane == 0) s_sum[simd_id] = acc;
        threadgroup_barrier(mem_flags::mem_threadgroup);

        %s block_sum = (simd_id == 0 && simd_lane < 4) ? s_sum[simd_lane] : 0.0f;
        if (simd_id == 0) block_sum = simdgroup_sum(block_sum);
        if (tid == 0) out[row] = block_sum;
    }
}
`, opts.KernelName, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision)
}

func generateMSLRoPEStoreKVKernel(opts CodegenOptions) string {
	return fmt.Sprintf(`kernel void %s(
    device %s* Q                       [[buffer(0)]],
    device %s* K                       [[buffer(1)]],
    device const %s* V                 [[buffer(2)]],
    device %s* kCache                  [[buffer(3)]],
    device %s* vCache                  [[buffer(4)]],
    constant int& pos                  [[buffer(5)]],
    constant int& numQHeads            [[buffer(6)]],
    constant int& numKVHeads           [[buffer(7)]],
    constant int& headDim              [[buffer(8)]],
    constant float& ropeTheta          [[buffer(9)]],
    constant int& maxSeqLen            [[buffer(10)]],
    uint headIdx                       [[threadgroup_position_in_grid]],
    uint pairIdx                       [[thread_position_in_threadgroup]]
) {
    if (headIdx >= uint(numQHeads) || pairIdx >= uint(headDim / 2)) return;

    float freq = 1.0f / pow(ropeTheta, float(2 * pairIdx) / float(headDim));
    float val = float(pos) * freq;
    float cosVal = cos(val);
    float sinVal = sin(val);

    uint qOffset0 = headIdx * headDim + pairIdx;
    uint qOffset1 = qOffset0 + headDim / 2;
    float q0 = Q[qOffset0];
    float q1 = Q[qOffset1];
    Q[qOffset0] = q0 * cosVal - q1 * sinVal;
    Q[qOffset1] = q0 * sinVal + q1 * cosVal;

    if (headIdx < uint(numKVHeads)) {
        uint kOffset0 = headIdx * headDim + pairIdx;
        uint kOffset1 = kOffset0 + headDim / 2;
        float k0 = K[kOffset0];
        float k1 = K[kOffset1];
        float rotK0 = k0 * cosVal - k1 * sinVal;
        float rotK1 = k0 * sinVal + k1 * cosVal;
        K[kOffset0] = rotK0;
        K[kOffset1] = rotK1;

        uint cacheIdx0 = (headIdx * maxSeqLen + pos) * headDim + pairIdx;
        uint cacheIdx1 = cacheIdx0 + headDim / 2;
        kCache[cacheIdx0] = rotK0;
        kCache[cacheIdx1] = rotK1;

        uint vOffset0 = headIdx * headDim + pairIdx;
        uint vOffset1 = vOffset0 + headDim / 2;
        vCache[cacheIdx0] = V[vOffset0];
        vCache[cacheIdx1] = V[vOffset1];
    }
}
`, opts.KernelName, opts.Precision, opts.Precision, opts.Precision, opts.Precision, opts.Precision)
}

type elementwiseCodegen struct {
	inputs      []string
	inputExprs  []*Expr
	index       map[string][]int
	precision   string
	uses        map[*Expr]int
	emitted     map[*Expr]string
	temporaries []string
}

func (g *elementwiseCodegen) emit(expr *Expr) (string, error) {
	if expr == nil {
		return "", fmt.Errorf("egraph: nil node in elementwise expression")
	}
	type frame struct {
		expr      *Expr
		nextChild int
		prepared  bool
	}
	if value, ok := g.emitted[expr]; ok {
		return value, nil
	}
	stack := []frame{{expr: expr}}
	active := map[*Expr]bool{expr: true}
	for len(stack) > 0 {
		current := &stack[len(stack)-1]
		node := current.expr
		if !current.prepared {
			switch node.Op {
			case "add", "mul":
				if len(node.Children) != 2 {
					return "", fmt.Errorf("egraph: MSL code generation for %s wants 2 inputs, got %d", node.Op, len(node.Children))
				}
			case "silu":
				if len(node.Children) != 1 {
					return "", fmt.Errorf("egraph: MSL code generation for silu wants 1 input, got %d", len(node.Children))
				}
			default:
				if len(node.Children) != 0 {
					return "", fmt.Errorf("egraph: no elementwise MSL code generator for %s", node.Op)
				}
				name := node.Op
				if value, ok := node.Data.(string); ok {
					name = value
				} else if node.Data != nil {
					name = fmt.Sprintf("%T:%#v", node.Data, node.Data)
				}
				index := -1
				for _, candidate := range g.index[name] {
					if g.inputExprs[candidate].Equal(node) {
						index = candidate
						break
					}
				}
				if index < 0 {
					index = len(g.inputs)
					g.index[name] = append(g.index[name], index)
					g.inputs = append(g.inputs, name)
					g.inputExprs = append(g.inputExprs, node)
				}
				g.emitted[node] = fmt.Sprintf("in%d[id]", index)
				delete(active, node)
				stack = stack[:len(stack)-1]
				if len(stack) > 0 {
					stack[len(stack)-1].nextChild++
				}
				continue
			}
			current.prepared = true
		}

		if current.nextChild < len(node.Children) {
			child := node.Children[current.nextChild]
			if child == nil {
				return "", fmt.Errorf("egraph: nil node in elementwise expression")
			}
			if _, ok := g.emitted[child]; ok {
				current.nextChild++
				continue
			}
			if active[child] {
				return "", fmt.Errorf("egraph: cycle in elementwise expression at %s", child.Op)
			}
			active[child] = true
			stack = append(stack, frame{expr: child})
			continue
		}

		children := make([]string, len(node.Children))
		for i, child := range node.Children {
			children[i] = g.emitted[child]
		}
		var value string
		switch node.Op {
		case "add":
			value = "(" + children[0] + " + " + children[1] + ")"
		case "mul":
			value = "(" + children[0] + " * " + children[1] + ")"
		case "silu":
			value = fmt.Sprintf("(%s / (1.0f + exp(-%s)))", children[0], children[0])
		}
		if g.uses[node] > 1 {
			name := fmt.Sprintf("tmp%d", len(g.temporaries))
			g.temporaries = append(g.temporaries, fmt.Sprintf("const %s %s = %s;", g.precision, name, value))
			value = name
		}
		g.emitted[node] = value
		delete(active, node)
		stack = stack[:len(stack)-1]
		if len(stack) > 0 {
			stack[len(stack)-1].nextChild++
		}
	}
	return g.emitted[expr], nil
}

func generateMSLElementwiseKernel(expr *Expr, opts CodegenOptions) (string, error) {
	gen := &elementwiseCodegen{
		index:     make(map[string][]int),
		precision: opts.Precision,
		uses:      expressionUses(expr),
		emitted:   make(map[*Expr]string),
	}
	result, err := gen.emit(expr)
	if err != nil {
		return "", err
	}
	var sb strings.Builder
	fmt.Fprintf(&sb, "kernel void %s(\n", opts.KernelName)
	for i := range gen.inputs {
		fmt.Fprintf(&sb, "    device const %s* in%d [[buffer(%d)]],\n", opts.Precision, i, i)
	}
	fmt.Fprintf(&sb, "    device %s* out [[buffer(%d)]],\n", opts.Precision, len(gen.inputs))
	sb.WriteString("    uint id [[thread_position_in_grid]]\n) {\n")
	for _, declaration := range gen.temporaries {
		fmt.Fprintf(&sb, "    %s\n", declaration)
	}
	fmt.Fprintf(&sb, "    out[id] = %s;\n}\n", result)
	return sb.String(), nil
}

func expressionUses(root *Expr) map[*Expr]int {
	uses := make(map[*Expr]int)
	if root == nil {
		return uses
	}
	uses[root] = 1
	seen := make(map[*Expr]bool)
	stack := []*Expr{root}
	for len(stack) > 0 {
		expr := stack[len(stack)-1]
		stack = stack[:len(stack)-1]
		if expr == nil || seen[expr] {
			continue
		}
		seen[expr] = true
		for _, child := range expr.Children {
			uses[child]++
			stack = append(stack, child)
		}
	}
	return uses
}

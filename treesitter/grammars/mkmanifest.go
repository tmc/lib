//go:build ignore

// Mkmanifest rewrites pins.gen.go, resolving each repository's latest
// release and recording the SHA-256 of its source archive. Run it with
// "go generate ./grammars". Set GITHUB_TOKEN to raise the API rate limit.
//
// It downloads every archive, so it is slow and needs the network. Review
// the diff before committing: a digest that changes without a version
// change means the archive itself changed.
package main

import (
	"archive/tar"
	"bytes"
	"compress/gzip"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"path"
	"slices"
	"strings"
)

// sources lists the grammars to pin. Subdir names the directory holding
// src for a repository that publishes more than one grammar.
var sources = []struct{ Name, Repo, Subdir string }{
	{"bash", "tree-sitter/tree-sitter-bash", ""},
	{"c", "tree-sitter/tree-sitter-c", ""},
	{"cpp", "tree-sitter/tree-sitter-cpp", ""},
	{"css", "tree-sitter/tree-sitter-css", ""},
	{"go", "tree-sitter/tree-sitter-go", ""},
	{"html", "tree-sitter/tree-sitter-html", ""},
	{"java", "tree-sitter/tree-sitter-java", ""},
	{"javascript", "tree-sitter/tree-sitter-javascript", ""},
	{"json", "tree-sitter/tree-sitter-json", ""},
	{"python", "tree-sitter/tree-sitter-python", ""},
	{"ruby", "tree-sitter/tree-sitter-ruby", ""},
	{"rust", "tree-sitter/tree-sitter-rust", ""},
	{"tsx", "tree-sitter/tree-sitter-typescript", "tsx"},
	{"typescript", "tree-sitter/tree-sitter-typescript", "typescript"},
}

const header = `// Code generated by mkmanifest.go. DO NOT EDIT.

package grammars

// pinned is the set of grammars Install can build: one entry per grammar,
// sorted by name, each naming an upstream release archive and the SHA-256
// of its bytes.
var pinned = []Grammar{
`

func main() {
	log.SetFlags(0)
	log.SetPrefix("mkmanifest: ")

	entries := slices.Clone(sources)
	slices.SortFunc(entries, func(a, b struct{ Name, Repo, Subdir string }) int {
		return strings.Compare(a.Name, b.Name)
	})

	var buf bytes.Buffer
	buf.WriteString(header)
	archives := make(map[string][]byte) // one download per repository and tag
	for _, s := range entries {
		tag, err := latestTag(s.Repo)
		if err != nil {
			log.Fatalf("%s: %v", s.Name, err)
		}
		url := fmt.Sprintf("https://github.com/%s/archive/refs/tags/%s.tar.gz", s.Repo, tag)
		body, ok := archives[url]
		if !ok {
			if body, err = get(url); err != nil {
				log.Fatalf("%s: %v", s.Name, err)
			}
			archives[url] = body
		}
		if err := checkSource(body, s.Subdir); err != nil {
			log.Fatalf("%s %s: %v", s.Name, tag, err)
		}
		sum := sha256.Sum256(body)
		fmt.Fprintf(&buf, "\t{\n\t\tName:    %q,\n\t\tVersion: %q,\n\t\tURL:     %q,\n\t\tSHA256:  %q,\n",
			s.Name, tag, url, hex.EncodeToString(sum[:]))
		if s.Subdir != "" {
			fmt.Fprintf(&buf, "\t\tSubdir:  %q,\n", s.Subdir)
		}
		buf.WriteString("\t},\n")
		log.Printf("%s %s", s.Name, tag)
	}
	buf.WriteString("}\n")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatalf("generated source does not parse: %v", err)
	}
	if err := os.WriteFile("pins.gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// latestTag returns the tag of a repository's latest release.
func latestTag(repo string) (string, error) {
	req, err := http.NewRequest(http.MethodGet, "https://api.github.com/repos/"+repo+"/releases/latest", nil)
	if err != nil {
		return "", err
	}
	req.Header.Set("Accept", "application/vnd.github+json")
	if tok := os.Getenv("GITHUB_TOKEN"); tok != "" {
		req.Header.Set("Authorization", "Bearer "+tok)
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return "", fmt.Errorf("%s: %s", req.URL, resp.Status)
	}
	var release struct {
		TagName string `json:"tag_name"`
	}
	if err := json.NewDecoder(resp.Body).Decode(&release); err != nil {
		return "", err
	}
	if release.TagName == "" {
		return "", fmt.Errorf("%s has no latest release tag", repo)
	}
	return release.TagName, nil
}

func get(url string) ([]byte, error) {
	resp, err := http.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s", url, resp.Status)
	}
	return io.ReadAll(resp.Body)
}

// checkSource reports whether the archive holds a generated parser where
// Build will look for it, so that a repository which moves its sources
// fails here rather than at install time.
func checkSource(archive []byte, subdir string) error {
	zr, err := gzip.NewReader(bytes.NewReader(archive))
	if err != nil {
		return err
	}
	defer zr.Close()
	want := path.Join(subdir, "src", "parser.c")
	tr := tar.NewReader(zr)
	for {
		h, err := tr.Next()
		if err == io.EOF {
			return fmt.Errorf("no %s in the archive", want)
		}
		if err != nil {
			return err
		}
		name := strings.TrimPrefix(h.Name, "./")
		if i := strings.Index(name, "/"); i >= 0 && name[i+1:] == want {
			return nil
		}
	}
}

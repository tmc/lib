type source struct {
	Name   string
	Repo   string
	Subdir string
	Asset  string
	Ref    string
}

const header = `// Code generated by mkmanifest.go. DO NOT EDIT.

package grammars

// pinned is the set of grammars Install can build: one entry per grammar,
// sorted by name, each naming an upstream release archive and the SHA-256
// of its bytes.
var pinned = []Grammar{
`

func main() {
	log.SetFlags(0)
	log.SetPrefix("mkmanifest: ")

	entries := slices.Clone(sources)
	slices.SortFunc(entries, func(a, b source) int { return strings.Compare(a.Name, b.Name) })

	var buf bytes.Buffer
	buf.WriteString(header)
	archives := make(map[string][]byte) // one download per repository and tag
	for _, s := range entries {
		tag := s.Ref
		if tag == "" {
			var err error
			if tag, err = latestTag(s.Repo); err != nil {
				log.Fatalf("%s: %v", s.Name, err)
			}
		}
		url := fmt.Sprintf("https://github.com/%s/archive/refs/tags/%s.tar.gz", s.Repo, tag)
		if s.Ref != "" {
			url = fmt.Sprintf("https://github.com/%s/archive/%s.tar.gz", s.Repo, tag)
		}
		if s.Asset != "" {
			url = fmt.Sprintf("https://github.com/%s/releases/download/%s/%s", s.Repo, tag, s.Asset)
		}
		body, ok := archives[url]
		if !ok {
			got, err := get(url)
			if err != nil {
				log.Fatalf("%s: %v", s.Name, err)
			}
			body = got
			archives[url] = body
		}
		if err := checkSource(body, s.Subdir); err != nil {
			log.Fatalf("%s %s: %v", s.Name, tag, err)
		}
		sum := sha256.Sum256(body)
		fmt.Fprintf(&buf, "\t{\n\t\tName:    %q,\n\t\tVersion: %q,\n\t\tURL:     %q,\n\t\tSHA256:  %q,\n",
			s.Name, tag, url, hex.EncodeToString(sum[:]))
		if s.Subdir != "" {
			fmt.Fprintf(&buf, "\t\tSubdir:  %q,\n", s.Subdir)
		}
		buf.WriteString("\t},\n")
		log.Printf("%s %s", s.Name, tag)
	}
	buf.WriteString("}\n")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatalf("generated source does not parse: %v", err)
	}
	if err := os.WriteFile("pins.gen.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// latestTag returns the tag of a repository's latest release.
func latestTag(repo string) (string, error) {
	req, err := http.NewRequest(http.MethodGet, "https://api.github.com/repos/"+repo+"/releases/latest", nil)
	if err != nil {
		return "", err
	}
	req.Header.Set("Accept", "application/vnd.github+json")
	if tok := os.Getenv("GITHUB_TOKEN"); tok != "" {
		req.Header.Set("Authorization", "Bearer "+tok)
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return "", err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return "", fmt.Errorf("%s: %s", req.URL, resp.Status)
	}
	var release struct {
		TagName string `json:"tag_name"`
	}
	if err := json.NewDecoder(resp.Body).Decode(&release); err != nil {
		return "", err
	}
	if release.TagName == "" {
		return "", fmt.Errorf("%s has no latest release tag", repo)
	}
	return release.TagName, nil
}

func get(url string) ([]byte, error) {
	resp, err := http.Get(url)
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s", url, resp.Status)
	}
	return io.ReadAll(resp.Body)
}

// checkSource reports whether the archive holds a generated parser where
// Build will look for it, so that a repository which moves its sources, or
// never commits them, fails here rather than at install time.
func checkSource(archive []byte, subdir string) error {
	zr, err := gzip.NewReader(bytes.NewReader(archive))
	if err != nil {
		return err
	}
	defer zr.Close()
	want := path.Join(subdir, "src", "parser.c")
	tr := tar.NewReader(zr)
	for {
		h, err := tr.Next()
		if err == io.EOF {
			return fmt.Errorf("no %s in the archive", want)
		}
		if err != nil {
			return err
		}
		// The archive may or may not wrap its contents in a directory.
		name := path.Clean(strings.TrimPrefix(h.Name, "./"))
		if name == want || strings.HasSuffix(name, "/"+want) {
			return nil
		}
	}
}
